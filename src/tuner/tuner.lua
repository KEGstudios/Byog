-- ---------------------------------------------------------------- probe (read-only research)
-- Question: could the settings tables be EXTENDED with new rows, instead of taking over spare ones?
-- That depends on how the game finds a row. If it keeps its own array of row pointers, that array
-- is somewhere in memory; this probe looks for every 8-byte value that points into the projectile,
-- damage and explosion tables and reports where such pointers sit and how they are arranged.
-- It reads memory only, once per session, when [settings] probe = true. Output: PROBE.txt.
-- positions (in 8-byte slots) whose value is hi:lo with lo inside [lo_min, lo_max)
local function find_pointers(words, slots, hi, lo_min, lo_max, out)
    local found = 0
    for i = 0, slots - 1 do
        if words[2 * i + 1] == hi then
            local lo = words[2 * i]
            if lo >= lo_min and lo < lo_max then
                found = found + 1
                out[found] = i
            end
        end
    end
    return found
end

-- ---- probe, part 2: where an index array lives and which code uses it (read-only)
-- Question: an array of row pointers indexed by row id has a fixed number of slots. Is it part of a
-- module (compiled in), what lies right before and after it, and which instructions refer to it?
-- The bytes around each reference show whether the game checks the id against a row count.
local MEM_COMMIT, MEM_IMAGE = 0x1000, 0x1000000
local CODE_CHUNK = 16384
local EXECUTE = { [0x10] = true, [0x20] = true, [0x40] = true, [0x80] = true }   -- PAGE_EXECUTE*
local NEIGHBOURS = 64            -- slots listed before and after an index array
local MAX_REFERENCES = 20000
local MAX_INDEXES = 6            -- index arrays analysed per table

local function buffer_u16(o) return A.buffer[o] + A.buffer[o + 1] * 256 end
local function buffer_u32(o) return buffer_u16(o) + buffer_u16(o + 2) * 65536 end

-- Sections of the PE32+ image loaded at `base` (PE/COFF header layout). -> sections, image size
local function image_sections(base)
    if not A.read(base, 64) or A.buffer[0] ~= 0x4D or A.buffer[1] ~= 0x5A then return nil end
    local header = buffer_u32(0x3C)
    if header < 64 or header > 4096 then return nil end
    if not A.read(base + header, 24 + 112) or buffer_u32(0) ~= 0x4550 then return nil end
    local count, optional = buffer_u16(6), buffer_u16(20)
    if buffer_u16(24) ~= 0x20B or count < 1 or count > 96 then return nil end
    local image_size = buffer_u32(24 + 56)
    if not A.read(base + header + 24 + optional, count * 40) then return nil end
    local sections = {}
    for n = 0, count - 1 do
        local o = n * 40
        local name = (ffi.string(A.buffer + o, 8):gsub('%z.*$', ''):gsub('[^%w%._$]', '?'))
        sections[#sections + 1] = { name = name, size = buffer_u32(o + 8), rva = buffer_u32(o + 12),
                                    flags = buffer_u32(o + 36) }
    end
    return sections, image_size
end

-- Every 4-byte value in `count` bytes of code that names an address inside [lo, hi) of the image:
-- either directly (offset from the image base) or as a displacement from the end of those 4 bytes.
local function in_windows(windows, target)
    for _, w in ipairs(windows) do
        if target >= w.lo and target < w.hi then return true end
    end
    return false
end

-- [lo, hi) spans all `windows`: one cheap comparison rejects almost every value.
local function scan_chunk(bytes, count, rva, lo, hi, windows, out)
    if count < 4 then return end
    local v = bytes[0] + bytes[1] * 256 + bytes[2] * 65536
    for i = 0, count - 4 do
        v = v + bytes[i + 3] * 16777216
        if v >= lo and v < hi then
            if #out < MAX_REFERENCES and in_windows(windows, v) then
                out[#out + 1] = { rva = rva + i, target = v, kind = 'image' }
            end
        else
            local target = rva + i + 4 + v
            if target >= 4294967296 then target = target - 4294967296 end
            if target >= lo and target < hi and #out < MAX_REFERENCES and in_windows(windows, target) then
                out[#out + 1] = { rva = rva + i, target = target, kind = 'rip' }
            end
        end
        v = (v - bytes[i]) / 256
    end
end

-- Reads every committed, executable region of the image once.
local function scan_references(image, lo, hi, windows)
    local cursor, limit = image.base, image.base + image.size
    while cursor < limit do
        local region = A.region(cursor)
        if not region or not region.size or region.size <= 0 then break end
        local stop = math.min(region.base + region.size, limit)
        if region.state == MEM_COMMIT and region.type == MEM_IMAGE and EXECUTE[region.protection] then
            local at = cursor
            while at < stop do
                local span = math.min(CODE_CHUNK, stop - at)
                local extra = (at + span < stop) and 3 or 0       -- a value may straddle two chunks
                if A.read(at, span + extra) then
                    image.scanned = image.scanned + span
                    scan_chunk(A.buffer, span + extra, at - image.base, lo, hi, windows, image.hits)
                else
                    image.unreadable = image.unreadable + span
                end
                at = at + span
                pause()
            end
        end
        if stop <= cursor then break end
        cursor = stop
        pause()
    end
end

local function hex_bytes(from, count)
    local parts = {}
    for i = from, from + count - 1 do parts[#parts + 1] = string.format('%02X', A.buffer[i]) end
    return table.concat(parts, ' ')
end

-- What an 8-byte slot holds, in words the report can show.
local function describe_slot(index, targets, image)
    local lo, hi = tonumber(A.words[2 * index]), tonumber(A.words[2 * index + 1])
    if hi == 0 and lo == 0 then return '0' end
    if hi >= 0x8000 then return string.format('0x%08X%08X', hi, lo) end
    local value = hi * 4294967296 + lo
    for _, t in ipairs(targets) do
        if value >= t.rows_at and value < t.rows_end and (value - t.rows_at) % t.stride == 0 then
            return t.name:sub(1, 1) .. tostring(t.ids[(value - t.rows_at) / t.stride])
        end
        if value >= t.from and value < t.to then return t.name:sub(1, 1) .. '+' .. (value - t.from) end
    end
    if image and value >= image.base and value < image.base + image.size then
        return 'img+' .. hex(value - image.base)
    end
    return hex(value)
end

-- `count` slots starting at `address`, only from pages that are in memory, private and readable.
local function describe_slots(address, count, targets, image)
    local first, last = address, address + count * 8 - 1
    if not A.readable_private(first) then first = last - last % 4096 end
    if not A.readable_private(last) then last = first - first % 4096 + 4095 end
    local slots = math.floor((last - first + 1) / 8)
    if first > last or slots < 1 or not A.readable_private(first) or not A.read(first, slots * 8) then
        return '(not readable)'
    end
    local parts = {}
    for i = 0, slots - 1 do parts[#parts + 1] = describe_slot(i, targets, image) end
    return (slots < count and ('(' .. slots .. ' of ' .. count .. ' readable) ') or '') .. table.concat(parts, ' ')
end

local function probe_indexes(L, targets)
    local images, order = {}, {}
    for _, t in ipairs(targets) do
        for _, x in ipairs(t.indexes) do
            x.region = A.region(x.at)
            local base = x.region and x.region.type == MEM_IMAGE and x.region.allocation or 0
            if base > 0 and not images[base] then
                local sections, size = image_sections(base)
                if sections and size and size > 0 then
                    images[base] = { base = base, size = size, sections = sections, arrays = {}, hits = {},
                                     scanned = 0, unreadable = 0, file = A.module_file(base) }
                    order[#order + 1] = images[base]
                end
            end
            if images[base] then
                x.image, x.rva = images[base], x.at - base
                table.insert(images[base].arrays, x)
            end
        end
        pause()
    end
    for _, image in ipairs(order) do
        local lo, hi, windows = image.size, 0, {}
        for _, x in ipairs(image.arrays) do
            windows[#windows + 1] = { lo = math.max(x.rva - 512, 0), hi = x.rva + x.slots * 8 + 512 }
            lo, hi = math.min(lo, windows[#windows].lo), math.max(hi, windows[#windows].hi)
        end
        scan_references(image, lo, hi, windows)
    end

    for _, image in ipairs(order) do
        local name = image.file and image.file:match('[^\\/]+$') or '?'
        L[#L + 1] = string.format('[module %s] base %s image size %s; code read: %.0f bytes, unreadable %.0f; '
            .. 'candidate references %d%s', name, hex(image.base), hex(image.size), image.scanned, image.unreadable,
            #image.hits, #image.hits >= MAX_REFERENCES and ' (list full)' or '')
        local parts = {}
        for _, s in ipairs(image.sections) do
            parts[#parts + 1] = string.format('%s rva %s size %s flags 0x%08X', s.name, hex(s.rva), hex(s.size), s.flags)
        end
        L[#L + 1] = 'sections: ' .. table.concat(parts, '; ')
        L[#L + 1] = ''
    end
    for _, t in ipairs(targets) do
        if #t.indexes == 0 then
            L[#L + 1] = '[index ' .. t.name .. '] no array indexed by row id was found'
            L[#L + 1] = ''
        end
        for _, x in ipairs(t.indexes) do
            local image, r = x.image, x.region
            L[#L + 1] = string.format('[index %s] at %s, %d slots, row id = slot %+d', t.name, hex(x.at), x.slots, x.id_by)
            L[#L + 1] = r and string.format('memory: type 0x%X (%s), protection 0x%02X, region %s size %s, allocation base %s',
                r.type, r.type == MEM_IMAGE and 'module image' or 'not a module', r.protection, hex(r.base), hex(r.size),
                hex(r.allocation)) or 'memory: no region information'
            if image then
                local where = 'no section'
                for _, s in ipairs(image.sections) do
                    if x.rva >= s.rva and x.rva < s.rva + s.size then
                        where = string.format('section %s, %.0f bytes after the array until the section ends', s.name,
                                              s.rva + s.size - (x.rva + x.slots * 8))
                    end
                end
                L[#L + 1] = string.format('module: %s, array at rva %s (%s)', image.file and image.file:match('[^\\/]+$') or '?',
                                          hex(x.rva), where)
            end
            L[#L + 1] = NEIGHBOURS .. ' slots before: ' .. describe_slots(x.at - NEIGHBOURS * 8, NEIGHBOURS, targets, image)
            L[#L + 1] = NEIGHBOURS .. ' slots after: ' .. describe_slots(x.at + x.slots * 8, NEIGHBOURS, targets, image)
            if image then
                -- references grouped by the place they name, relative to the array's first slot
                local size, groups, keys = x.slots * 8, {}, {}
                for _, h in ipairs(image.hits) do
                    local offset = h.target - x.rva
                    if offset >= -512 and offset < size + 512 then
                        if not groups[offset] then groups[offset] = {}; keys[#keys + 1] = offset end
                        table.insert(groups[offset], h)
                    end
                end
                table.sort(keys)
                local others = {}
                for _, offset in ipairs(keys) do
                    local group = groups[offset]
                    local near = (offset >= -16 and offset <= 16) or (offset >= size - 16 and offset <= size + 16)
                    if near then
                        L[#L + 1] = string.format('code naming array %+d: %d', offset, #group)
                        for n = 1, math.min(#group, 8) do
                            local h = group[n]
                            local text = '(not readable)'
                            if A.read(image.base + h.rva - 48, 76) then
                                text = hex_bytes(0, 48) .. ' [' .. hex_bytes(48, 4) .. '] ' .. hex_bytes(52, 24)
                            end
                            L[#L + 1] = string.format('  %s at rva %s: %s', h.kind, hex(h.rva), text)
                        end
                    elseif #group >= 2 and #others < 40 then
                        others[#others + 1] = string.format('%+d x%d', offset, #group)
                    end
                    pause()
                end
                L[#L + 1] = 'other places named twice or more (array offset xcount): ' .. table.concat(others, ', ')
            end
            L[#L + 1] = ''
            pause()
        end
    end
end

local PROBE_TABLES = { 'ProjectileSettings', 'DamageSettings', 'ExplosionSettings' }

local function run_probe()
    local targets = {}
    for _, name in ipairs(PROBE_TABLES) do
        local spec = SPECS[name]
        local before = #targets
        for _, block in ipairs(spec and spec.blocks or {}) do
            if parse_block(block) then
                local ids = {}
                for id, row in pairs(block.index) do ids[row] = id end
                targets[#targets + 1] = { name = name, block = block, ids = ids, stride = spec.stride,
                    rows_at = block.records_at, rows_end = block.records_at + block.count * spec.stride,
                    from = block.address, to = block.limit, hits = {}, total = 0, indexes = {} }
            end
        end
        if #targets == before then
            -- some tables only exist while a mission is loaded: wait for all of them
            probe.note = 'waiting for ' .. name .. ', which is not loaded yet'
            return false
        end
    end
    probe.note = nil
    local lowest, highest = targets[1].from, targets[1].to
    for _, t in ipairs(targets) do
        if t.from < lowest then lowest = t.from end
        if t.to > highest then highest = t.to end
    end
    local hi = math.floor(lowest / 4294967296)
    if math.floor((highest - 1) / 4294967296) ~= hi then
        probe.state, probe.note = 'skipped', 'the tables straddle a 4 GB boundary'
        return true
    end
    local lo_min, lo_max = lowest - hi * 4294967296, highest - hi * 4294967296
    probe.state, probe.bytes, probe.allocations = 'running', 0, 0
    local started, slots_found = A.now(), {}
    local cursor = ADDRESS_START
    while cursor < ADDRESS_END do
        local base, size, allocated = A.allocation(cursor)
        if not base then break end
        if allocated then
            probe.allocations = probe.allocations + 1
            local offset = 0
            while offset < size do
                local span = math.min(FILE_CHUNK, size - offset)
                local count = math.ceil(span / 4096)
                local usable = A.pages(base + offset, count)
                local k = 1
                while usable and k <= count do
                    if usable[k] then
                        local last = k
                        while last < count and usable[last + 1] do last = last + 1 end
                        local at, bytes = base + offset + (k - 1) * 4096, (last - k + 1) * 4096
                        if A.read(at, bytes) then
                            probe.bytes = probe.bytes + bytes
                            local found = find_pointers(A.words, bytes / 8, hi, lo_min, lo_max, slots_found)
                            for n = 1, found do
                                local where = at + slots_found[n] * 8
                                local value = hi * 4294967296 + A.words[2 * slots_found[n]]
                                -- copies of memory inside our own read buffer are not the game's pointers
                                if where < A.buffer_address or where >= A.buffer_address + A.buffer_size then
                                    for _, t in ipairs(targets) do
                                        if value >= t.from and value < t.to then
                                            t.total = t.total + 1
                                            if #t.hits < 6000 then t.hits[#t.hits + 1] = { where = where, value = value } end
                                        end
                                    end
                                end
                            end
                        end
                        k = last + 1
                    else
                        k = k + 1
                    end
                end
                offset = offset + FILE_CHUNK
                pause()
            end
        end
        local following = base + size
        if following <= cursor then following = cursor + 4096 end
        cursor = following
        pause()
    end

    -- report
    local L = { MOD.title .. ' v' .. MOD.version .. ' probe (read-only)',
                string.format('swept %.0f bytes in %d allocations, %.1f s', probe.bytes, probe.allocations,
                              A.now() - started), '' }
    for _, t in ipairs(targets) do
        table.sort(t.hits, function(x, y) return x.where < y.where end)
        local header, row_start, inside_rows, elsewhere, internal = 0, 0, 0, 0, 0
        for _, h in ipairs(t.hits) do
            if h.where >= t.from and h.where < t.to then internal = internal + 1 end
            if h.value == t.block.address or h.value == t.block.address + 24 then header = header + 1
            elseif h.value >= t.rows_at and h.value < t.rows_end then
                if (h.value - t.rows_at) % t.stride == 0 then row_start = row_start + 1
                else inside_rows = inside_rows + 1 end
            else elsewhere = elsewhere + 1 end
        end
        L[#L + 1] = string.format('[%s] block %s rows %s count %d stride %d', t.name, hex(t.block.address),
                                  hex(t.rows_at), t.block.count, t.stride)
        L[#L + 1] = string.format('pointers into it: %d (kept %d): to the block start %d, to a row start %d, '
            .. 'inside a row %d, elsewhere in the block %d; located inside the block itself %d', t.total, #t.hits,
            header, row_start, inside_rows, elsewhere, internal)
        -- runs of pointers in consecutive 8-byte slots: these are arrays
        local runs, i = {}, 1
        while i <= #t.hits do
            local j = i
            while j < #t.hits and t.hits[j + 1].where == t.hits[j].where + 8 do j = j + 1 end
            if j - i + 1 >= 3 then runs[#runs + 1] = { first = i, last = j } end
            i = j + 1
        end
        table.sort(runs, function(x, y) return (x.last - x.first) > (y.last - y.first) end)
        L[#L + 1] = 'arrays of pointers (3 or more in consecutive slots): ' .. #runs
        for n = 1, math.min(#runs, 25) do
            local run = runs[n]
            -- an index array need not start at id 0: look for "id = slot + constant"
            local length, id_shift, row_shift, starts, sample = run.last - run.first + 1, {}, {}, 0, {}
            for k = run.first, run.last do
                local h = t.hits[k]
                local slot = k - run.first
                if h.value >= t.rows_at and h.value < t.rows_end and (h.value - t.rows_at) % t.stride == 0 then
                    starts = starts + 1
                    local row = (h.value - t.rows_at) / t.stride
                    row_shift[row - slot] = (row_shift[row - slot] or 0) + 1
                    if t.ids[row] then id_shift[t.ids[row] - slot] = (id_shift[t.ids[row] - slot] or 0) + 1 end
                    if #sample < 10 then sample[#sample + 1] = 'row' .. row .. '=id' .. tostring(t.ids[row]) end
                elseif #sample < 10 then
                    sample[#sample + 1] = '+' .. (h.value - t.from)
                end
            end
            local function best(shifts)
                local shift, count = 0, 0
                for value, n in pairs(shifts) do
                    if n > count then shift, count = value, n end
                end
                return shift, count
            end
            local id_by, id_count = best(id_shift)
            local row_by, row_count = best(row_shift)
            if length >= 16 and id_count * 10 >= length * 9 and #t.indexes < MAX_INDEXES then
                t.indexes[#t.indexes + 1] = { at = t.hits[run.first].where, slots = length, id_by = id_by }
            end
            L[#L + 1] = string.format('  at %s: %d pointers, %d to row starts; row id = slot %+d for %d of them, '
                .. 'row order = slot %+d for %d; first: %s', hex(t.hits[run.first].where), length, starts, id_by, id_count,
                row_by, row_count, table.concat(sample, ' '))
        end
        local singles = {}
        for k = 1, #t.hits do
            local h = t.hits[k]
            local alone = (k == 1 or t.hits[k - 1].where ~= h.where - 8) and (k == #t.hits or t.hits[k + 1].where ~= h.where + 8)
            if alone and #singles < 30 then singles[#singles + 1] = hex(h.where) .. '->+' .. (h.value - t.from) end
        end
        L[#L + 1] = 'single pointers (first 30): ' .. table.concat(singles, ' ')
        L[#L + 1] = ''
        pause()
    end
    state.step = 'probe: reading the code that uses the index arrays'
    local ok_indexes, why_indexes = pcall(probe_indexes, L, targets)
    if not ok_indexes then L[#L + 1] = 'index analysis failed: ' .. tostring(why_indexes) end
    write_file('PROBE.txt', table.concat(L, '\r\n') .. '\r\n')
    probe.state = 'done'
    log('probe finished: ' .. string.format('%.0f', probe.bytes) .. ' bytes swept')
    return true
end

-- ---------------------------------------------------------------- census (read-only research)
-- Question: which rows of a settings table does nothing refer to? Offline we only have part of the
-- game's data. The type library, which is complete, names every type that can hold such a row id
-- (the C lines of the data); this census finds every block of those types in memory, reads each id
-- and counts the references per row. It reads memory only, once per session, when
-- [settings] census = true. Output: CENSUS.txt.
local CENSUS_MAX_ARRAY = 100000

-- Every block of a census type, wherever it is in memory. -> { census entry -> blocks }, bytes read
local function census_blocks()
    local by_type, seen, found, bytes = {}, {}, {}, 0
    for _, c in ipairs(CENSUS) do by_type[c.type], found[c] = c, {} end
    local hits = {}
    local cursor = ADDRESS_START
    while cursor < ADDRESS_END do
        local base, size, allocated = A.allocation(cursor)
        if not base then break end
        if allocated then
            local offset = 0
            while offset < size do
                local span = math.min(FILE_CHUNK, size - offset)
                local count = math.ceil(span / 4096)
                local usable = A.pages(base + offset, count)
                local k = 1
                while usable and k <= count do
                    if usable[k] then
                        -- the run of usable pages k .. last is read in one go
                        local last = k
                        while last < count and usable[last + 1] do last = last + 1 end
                        local at, length = base + offset + (k - 1) * 4096, (last - k + 1) * 4096
                        if A.read(at, length) then
                            bytes = bytes + length
                            local words, n = A.words, 0
                            for i = 0, length / 4 - 1 do
                                if words[i] == LDLD then
                                    n = n + 1
                                    hits[n] = i
                                end
                            end
                            for h = 1, n do
                                local where = at + hits[h] * 4
                                -- a copy inside our own read buffer is not a table; the rest of a header
                                -- may lie beyond this read, so it is read on its own
                                if (where < A.buffer_address or where >= A.buffer_address + A.buffer_size)
                                    and not seen[where] and A.u32(where + 4) == 1 then
                                    local c, block_size = by_type[A.u32(where + 8) or 0], A.u32(where + 12)
                                    if c and block_size and block_size > 0 and block_size <= MAX_BLOCK then
                                        seen[where] = true
                                        found[c][#found[c] + 1] = { address = where, type = c.type, size = block_size, spec = c }
                                    end
                                end
                                if h % 32 == 0 then pause() end      -- hundreds of small blocks can sit side by side
                            end
                        end
                        k = last + 1
                    else
                        k = k + 1
                    end
                end
                offset = offset + FILE_CHUNK
                pause()
            end
        end
        local following = base + size
        if following <= cursor then following = cursor + 4096 end
        cursor = following
        pause()
    end
    return found, bytes
end

-- Follows one path from `at` and counts the id it ends at.
local function census_follow(at, steps, k, block, tally)
    while k <= #steps do
        local step = steps[k]
        if step.array then
            local pointer, count = A.u64(at), A.u64(at + 8)
            if not pointer or not count then
                tally.unreadable = tally.unreadable + 1
                return
            end
            if count == 0 then return end
            if pointer < block.size then pointer = block.address + 24 + pointer end      -- file form
            if count > CENSUS_MAX_ARRAY or pointer < block.address
                or pointer + count * step.array > block.address + 24 + block.size then
                tally.outside = tally.outside + 1      -- an array that is not inside its block: not followed
                return
            end
            for n = 0, count - 1 do
                census_follow(pointer + n * step.array, steps, k + 1, block, tally)
                if n % 64 == 63 then pause() end
            end
            return
        end
        at = at + step.add
        k = k + 1
    end
    local id = A.u32(at)
    tally.values = tally.values + 1
    if id == nil then
        tally.unreadable = tally.unreadable + 1
    elseif id ~= 0 then
        tally.references = tally.references + 1
        if id > tally.highest then
            tally.beyond = tally.beyond + 1
        else
            tally.rows[id] = (tally.rows[id] or 0) + 1
            tally.own[id] = true
        end
    end
end

local function census_block(block, c, tally)
    local records_at, count, stride = block.address + 24, 1, 0
    if c.shape ~= 'O' then
        local ok
        if c.shape == 'K' then ok = parse_keyed(block) else ok = parse_rows(block) end
        if not ok then
            tally.unparsed = tally.unparsed + 1
            return
        end
        records_at, count, stride = block.records_at, block.count, c.stride
    end
    tally.records = tally.records + count
    for r = 0, count - 1 do
        for _, steps in ipairs(c.paths) do census_follow(records_at + r * stride, steps, 1, block, tally) end
        if r % 16 == 15 then pause() end
    end
end

local function number_lines(L, numbers, per_line)
    for from = 1, #numbers, per_line do
        L[#L + 1] = '  ' .. table.concat(numbers, ' ', from, math.min(from + per_line - 1, #numbers))
    end
end

-- -> true when finished (or impossible), false when the tables are not loaded yet
local function run_census()
    local started, targets, names = A.now(), {}, {}
    for target, table_name in pairs(CENSUS_TABLE) do
        local spec, ids, rows = SPECS[table_name], nil, 0
        for _, block in ipairs(spec and spec.blocks or {}) do
            if parse_block(block) then
                ids, rows = ids or {}, block.count
                for id in pairs(block.index) do ids[id] = true end
            end
        end
        if not ids then
            census.note = 'waiting for ' .. table_name .. ', which is not loaded yet'
            return false
        end
        local highest = 0
        for id in pairs(ids) do if id > highest then highest = id end end
        targets[target] = { table = table_name, ids = ids, rows = rows, highest = highest, refs = {} }
        names[#names + 1] = target
    end
    table.sort(names)
    census.note, census.state = nil, 'running'
    state.step = 'census: sweeping memory for tables'
    local found, bytes = census_blocks()
    census.bytes = bytes
    local L = { MOD.title .. ' v' .. MOD.version .. ' census (read-only)' }
    for _, target in ipairs(names) do
        local t = targets[target]
        L[#L + 1] = ''
        L[#L + 1] = string.format('[%s] %s: %d rows, highest id %d', target, t.table, t.rows, t.highest)
        for _, c in ipairs(CENSUS) do
            if c.target == target then
                state.step = 'census: reading ' .. c.name
                local tally = { records = 0, values = 0, references = 0, outside = 0, unreadable = 0, beyond = 0,
                                unparsed = 0, highest = t.highest, rows = t.refs, own = {} }
                for _, block in ipairs(found[c]) do census_block(block, c, tally) end
                local verdict
                if #found[c] == 0 then verdict = 'NOT FOUND in memory'
                elseif not c.offline then verdict = 'not in the offline data'
                elseif tally.references == c.offline * #found[c] then verdict = 'as offline'
                else verdict = 'DIFFERENT from offline' end
                L[#L + 1] = string.format('%s (%s): blocks=%d records=%d values=%d references=%d offline=%s  %s'
                    .. '  [arrays outside their block=%d unreadable=%d ids beyond the table=%d unparsed blocks=%d]',
                    c.name, c.shape, #found[c], tally.records, tally.values, tally.references,
                    c.offline and tostring(c.offline) or '-', verdict, tally.outside, tally.unreadable, tally.beyond,
                    tally.unparsed)
                local own = {}
                for id in pairs(tally.own) do own[#own + 1] = id end
                table.sort(own)
                if #own > 0 then number_lines(L, own, 30) end
                pause()
            end
        end
        local free, counts = {}, {}
        for id = 1, t.highest do
            if t.ids[id] then
                if not t.refs[id] then free[#free + 1] = id end
                counts[#counts + 1] = id .. '=' .. (t.refs[id] or 0)
            end
        end
        L[#L + 1] = ''
        L[#L + 1] = 'rows no table refers to: ' .. #free
        number_lines(L, free, 30)
        L[#L + 1] = 'references per row (id=count):'
        number_lines(L, counts, 16)
    end
    L[#L + 1] = ''
    L[#L + 1] = string.format('swept %.0f bytes, %.1f s', bytes, A.now() - started)
    write_file('CENSUS.txt', table.concat(L, '\r\n') .. '\r\n')
    census.state = 'done'
    log('census finished: ' .. string.format('%.0f', bytes) .. ' bytes swept')
    return true
end

-- ---------------------------------------------------------------- globals (read-only research)
-- Question for the in-game menu: what does the game's Lua offer (drawing, text, input)? With
-- [settings] dump_globals = true the names and types of the global tables are written to GLOBALS.txt,
-- once per session. Nothing is called and nothing is changed.
local globals_dumped = false
local function dump_globals()
    globals_dumped = true
    local names = {}
    for name in pairs(_G) do
        if type(name) == 'string' then names[#names + 1] = name end
    end
    table.sort(names)
    local L = { MOD.title .. ' v' .. MOD.version .. ' globals (read-only)', #names .. ' global names', '' }
    for n, name in ipairs(names) do
        local value = rawget(_G, name)
        if type(value) == 'table' then
            local keys = {}
            for key, member in pairs(value) do
                if #keys < 400 then keys[#keys + 1] = tostring(key) .. ':' .. type(member):sub(1, 1) end
            end
            table.sort(keys)
            L[#L + 1] = name .. ' (table, ' .. #keys .. ' keys) ' .. table.concat(keys, ' ')
            -- one level deeper for the engine's and the other frameworks' tables: their function names
            if name == 'stingray' or name:sub(1, 10) == 'HD2Runtime' or name == 'CowboyBingusModLoader' then
                local inner = {}
                for key, member in pairs(value) do
                    if type(member) == 'table' and type(key) == 'string' then inner[#inner + 1] = key end
                end
                table.sort(inner)
                for k, key in ipairs(inner) do
                    local members = {}
                    for member, v in pairs(value[key]) do
                        if #members < 300 then members[#members + 1] = tostring(member) .. ':' .. type(v):sub(1, 1) end
                    end
                    table.sort(members)
                    L[#L + 1] = '  ' .. name .. '.' .. key .. ' (' .. #members .. ') ' .. table.concat(members, ' ')
                    if k % 8 == 0 then pause() end
                end
            end
        else
            L[#L + 1] = name .. ' (' .. type(value) .. ')'
        end
        if n % 8 == 0 then pause() end
    end
    write_file('GLOBALS.txt', table.concat(L, '\r\n') .. '\r\n')
    log('globals written: ' .. #names .. ' names')
end

-- ---------------------------------------------------------------- the worker
local wake = { at = 0, reload = false, config_check_at = 0 }

local function sleep(seconds)
    wake.at = A.now() + seconds
    coroutine.yield()
end

local function worker_main()
    state.step = 'reading the built-in data'
    parse_data()
    state.phase, state.step = 'checking the build', 'hashing the game files'
    write_status(true)
    check_build()
    state.step = 'reading config.txt'
    load_config()
    state.step = 'writing catalog.txt'
    write_catalog()
    local backoff, next_rescan = 1, 0
    while true do
        if wake.reload then
            wake.reload = false
            state.step = 'reading config.txt'
            load_config()
            backoff = 1
        end
        if config.dump_globals and not globals_dumped then
            local ok_globals, why_globals = pcall(dump_globals)
            if not ok_globals then log('globals: ' .. tostring(why_globals)) end
        end
        if build.state ~= 'verified' then
            state.phase = 'refused'
            write_status()
            sleep(3600)
        elseif config.probe and probe.state == 'off' then
            -- research request: find the tables, then sweep memory once for pointers into them
            state.phase, state.step = 'probing', 'probe: searching for tables'
            write_status()
            find_tables()
            state.step = 'probe: sweeping memory'
            local ok_probe, done = pcall(run_probe)
            if not ok_probe then
                probe.state, probe.note = 'failed', tostring(done)
                log('probe failed: ' .. tostring(done))
            elseif not done then
                probe.state = 'off'          -- the tables are not loaded yet: try again later
                write_status(true)
                sleep(15)
            end
            write_status(true)
        elseif config.census and census.state == 'off' then
            -- research request: count, in every table that can hold one, the references to each row
            state.phase, state.step = 'probing', 'census: searching for tables'
            write_status()
            find_tables()
            local ok_census, done = pcall(run_census)
            if not ok_census then
                census.state, census.note = 'failed', tostring(done)
                log('census failed: ' .. tostring(done))
            elseif not done then
                census.state = 'off'         -- the tables are not loaded yet: try again later
                write_status(true)
                sleep(15)
            end
            write_status(true)
        else
            local missing = missing_tables()
            local have_work = next(desired) ~= nil or next(applied) ~= nil
            local rescan_due = have_work and config.rescan > 0 and A.now() >= next_rescan
            if have_work and (#missing > 0 or state.lost or rescan_due) then
                state.phase, state.step = 'searching', 'searching for tables'
                find_tables()
                state.lost = false
                next_rescan = A.now() + (config.rescan > 0 and config.rescan or 0)
            end
            if have_work then
                state.phase, state.step = 'applying', 'applying values'
                sync()
                state.step = 'writing STATUS.txt'
            end
            if state.report_pending then
                local ok_report, why_report = pcall(log_results)
                if not ok_report then log('report: ' .. tostring(why_report)) end
            end
            missing = missing_tables()
            if not have_work then
                state.phase = 'idle'
                write_status()
                sleep(3600)
            elseif #missing > 0 then
                state.phase = 'waiting for tables'
                write_status()
                sleep(SEARCH_BACKOFF[math.min(backoff, #SEARCH_BACKOFF)])
                backoff = backoff + 1
            else
                backoff = 1
                state.phase = 'applied'
                write_status()
                -- asleep: only cheap read-backs until something needs attention
                while not wake.reload do
                    sleep(RECHECK_SECONDS)
                    if wake.reload then break end
                    state.step = 'rechecking applied values'
                    local result = recheck()
                    if result == 'lost' then
                        state.lost = true
                        log('a patched table is gone (map load?): searching again')
                        break
                    elseif result == 'changed' then
                        log('a patched value was changed back: applying again')
                        break
                    elseif config.rescan > 0 and A.now() >= next_rescan then
                        break
                    end
                end
            end
        end
    end
end

