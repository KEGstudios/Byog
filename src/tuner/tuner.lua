-- HD2-Addon: mods/keg/stat_tuner
-- HD2 Stat Tuner: changes existing weapon / throwable values in the game's memory from a config
-- file. Files, all in %LOCALAPPDATA%\HD2StatTuner:
--   config.txt    what to change (see docs/CONFIG-FORMAT.md; a template is created on first run)
--   STATUS.txt    what happened: first line is the verdict
--   catalog.txt   every item and stat this build knows, with the game's value and allowed range
--   tuner.log     developer log
-- Requires Bingus Shared Loader (API 1). Runs on LuaJIT (Lua 5.1 syntax only).
--
-- Safety rules this file implements:
--   * nothing is written unless the game executable and game.dll hash to a verified build;
--   * every write is range-checked before, done through the OS (never a raw pointer), read back
--     with an independent decoder, and undone when the config no longer asks for it;
--   * the game keeps its component tables in read-only pages: such a page is made writable for
--     the one 4-byte write and put back to read-only at once (checked);
--   * tables are located by 'LDLD' + version + type hash only; counts and layouts are derived;
--   * all work is sliced: at most FRAME_BUDGET seconds on every STEP_EVERY-th frame.

local MOD = {
    title = 'HD2 Stat Tuner', version = '@@VERSION@@', global = 'HD2StatTuner',
    dir = 'HD2StatTuner', status = 'STATUS.txt', log = 'tuner.log', config = 'config.txt',
    catalog = 'catalog.txt',
}
-- Generated by tools/gen_tuner_data.py: verified builds (V), tables (T), items (I), fields (F),
-- ranges (R), aliases (A).
local DATA = [==[
@@DATA@@]==]

if rawget(_G, MOD.global) then return end

-- ---------------------------------------------------------------- tuning
local START_FRAME = 120          -- let the game start before touching anything
local STEP_EVERY = 2             -- heavy work on every 2nd frame only
local FRAME_BUDGET = 0.001       -- seconds of work per working frame
local RECHECK_SECONDS = 5        -- read back every applied value this often
local RELOAD_DEBOUNCE = 0.75     -- seconds: further presses of the reload key within this time are ignored
local SEARCH_BACKOFF = { 5, 10, 20, 30 }   -- seconds between searches while tables are missing
local DEFAULT_RESCAN_SECONDS = 120          -- look for new copies of patched tables this often
local MAX_BLOCK = 0x10000000
local ADDRESS_START, ADDRESS_END = 0x10000, 0x7FFFFFFF0000
local LDLD = 0x444C444C          -- 'LDLD' read as a little-endian u32
local PAGE_READONLY, PAGE_READWRITE = 0x02, 0x04
local FILE_CHUNK = 262144
local HASH_CHUNK = 65536         -- bytes hashed per step while checking the build

local state = {
    title = MOD.title, version = MOD.version, phase = 'starting', verdict = 'WAITING',
    frame = 0, errors = 0, writes = 0, restores = 0, rewrites = 0, passes = 0, unlocks = 0, left_open = 0,
    reloads = 0,
    worst_frame = 0, busy_frames = 0, busy_seconds = 0,
}
rawset(_G, MOD.global, state)

-- ---------------------------------------------------------------- log
local log_lines, log_seen, log_dirty = {}, {}, false
local function log(message)
    message = tostring(message)
    local n = (log_seen[message] or 0) + 1
    log_seen[message] = n
    if n > 3 or #log_lines >= 4000 then return end
    if n == 3 then message = message .. ' (further repeats not logged)' end
    log_lines[#log_lines + 1] = '[frame ' .. state.frame .. '] ' .. message
    log_dirty = true
end

-- Addresses do not fit a 32-bit %X; print the two halves.
local function hex(n)
    local high = math.floor(n / 4294967296)
    if high > 0 then return string.format('0x%X%08X', high, n - high * 4294967296) end
    return string.format('0x%X', n)
end

local function trim(text) return (text:gsub('^%s+', ''):gsub('%s+$', '')) end

-- ---------------------------------------------------------------- numbers
-- Independent IEEE-754 decoder: read-back checks never share code with the encoder.
local function bits_to_f32(bits)
    local sign = 1
    if bits >= 2147483648 then sign = -1; bits = bits - 2147483648 end
    local exponent = math.floor(bits / 8388608)
    local mantissa = bits - exponent * 8388608
    if exponent == 255 then
        if mantissa == 0 then return sign * math.huge end
        return 0 / 0
    end
    if exponent == 0 then return sign * mantissa * 2 ^ -149 end
    return sign * (1 + mantissa / 8388608) * 2 ^ (exponent - 127)
end

local function close_enough(a, b)
    if a ~= a or b ~= b then return false end
    return math.abs(a - b) <= 0.00001 * math.max(1, math.abs(b))
end

local function same_value(storage, a, b)
    if a == nil or b == nil then return false end
    if storage == 'f32' then return close_enough(a, b) end
    return a == b
end

local function show(value, storage)
    if value == nil then return '?' end
    if storage == 'f32' then
        local text = string.format('%.4f', value):gsub('0+$', ''):gsub('%.$', '')
        return text
    end
    return string.format('%.0f', value)
end

-- ---------------------------------------------------------------- windows api
local ffi_ok, ffi = pcall(require, 'ffi')
local A = nil

local function build_api()
    local a = {}
    local cvoid = ffi.typeof('const void *')
    local void = ffi.typeof('void *')

    -- Every function is fetched by name and cast to OUR signature, so declarations made by
    -- other addons can never change how we call it. Tests inject their own resolver.
    local resolve = rawget(_G, 'HD2ST_TEST_RESOLVER')
    if type(resolve) ~= 'function' then
        for _, declaration in ipairs({
            'void *GetModuleHandleA(const char *name);',
            'void *LoadLibraryA(const char *name);',
            'void *GetProcAddress(void *module, const char *name);',
        }) do pcall(ffi.cdef, declaration) end
        local k32 = ffi.load('kernel32')
        local get_module = ffi.cast('void *(*)(const char *)', k32.GetModuleHandleA)
        local load_library = ffi.cast('void *(*)(const char *)', k32.LoadLibraryA)
        local get_proc = ffi.cast('void *(*)(void *, const char *)', k32.GetProcAddress)
        resolve = function(dll, name, signature)
            local module = get_module(dll)
            if module == nil then module = load_library(dll) end
            if module == nil then error('cannot load ' .. dll) end
            local address = get_proc(module, name)
            if address == nil then error(name .. ' not found in ' .. dll) end
            return ffi.cast(signature, address)
        end
    end
    local K = 'kernel32.dll'
    local get_process = resolve(K, 'GetCurrentProcess', 'void *(*)(void)')
    local get_process_id = resolve(K, 'GetCurrentProcessId', 'uint32_t (*)(void)')
    local read_memory = resolve(K, 'ReadProcessMemory', 'int (*)(void *, const void *, void *, size_t, size_t *)')
    local write_memory = resolve(K, 'WriteProcessMemory', 'int (*)(void *, void *, const void *, size_t, size_t *)')
    local virtual_query = resolve(K, 'VirtualQuery', 'size_t (*)(const void *, void *, size_t)')
    local virtual_protect = resolve(K, 'VirtualProtect', 'int (*)(void *, size_t, uint32_t, uint32_t *)')
    local working_set = resolve(K, 'K32QueryWorkingSetEx', 'int (*)(void *, void *, uint32_t)')
    local create_directory = resolve(K, 'CreateDirectoryA', 'int (*)(const char *, void *)')
    local get_last_error = resolve(K, 'GetLastError', 'uint32_t (*)(void)')
    local perf_counter = resolve(K, 'QueryPerformanceCounter', 'int (*)(int64_t *)')
    local perf_frequency = resolve(K, 'QueryPerformanceFrequency', 'int (*)(int64_t *)')
    local module_handle = resolve(K, 'GetModuleHandleA', 'void *(*)(const char *)')
    local module_file_name = resolve(K, 'GetModuleFileNameA', 'uint32_t (*)(void *, char *, uint32_t)')
    local create_file = resolve(K, 'CreateFileA',
        'void *(*)(const char *, uint32_t, uint32_t, void *, uint32_t, uint32_t, void *)')
    local read_file = resolve(K, 'ReadFile', 'int (*)(void *, void *, uint32_t, uint32_t *, void *)')
    local file_size = resolve(K, 'GetFileSizeEx', 'int (*)(void *, int64_t *)')
    local close_handle = resolve(K, 'CloseHandle', 'int (*)(void *)')
    local query_memory = resolve('ntdll.dll', 'NtQueryVirtualMemory',
        'int32_t (*)(void *, const void *, int32_t, void *, size_t, size_t *)')
    local U = 'user32.dll'
    local key_state = resolve(U, 'GetAsyncKeyState', 'int16_t (*)(int32_t)')
    local foreground_window = resolve(U, 'GetForegroundWindow', 'void *(*)(void)')
    local window_process = resolve(U, 'GetWindowThreadProcessId', 'uint32_t (*)(void *, uint32_t *)')

    local process = get_process()
    local got = ffi.new('size_t[1]')

    local ticks, frequency = ffi.new('int64_t[1]'), ffi.new('int64_t[1]')
    perf_frequency(frequency)
    local per_second = tonumber(frequency[0])
    if not per_second or per_second <= 0 then error('no performance counter') end
    function a.now()
        perf_counter(ticks)
        return tonumber(ticks[0]) / per_second
    end

    -- The allocation holding `address`: base, size, true. For free memory: base, size, false.
    -- NtQueryVirtualMemory's region information costs the same for any allocation size;
    -- VirtualQuery is only used for free memory (in-game it took 9.9 ms on one huge region).
    local info = ffi.new('uint64_t[6]')
    local info32 = ffi.cast('uint32_t *', info)
    local returned = ffi.new('size_t[1]')
    function a.allocation(address)
        local pointer = ffi.cast(cvoid, address)
        if query_memory(process, pointer, 3, info, 48, returned) == 0
            or query_memory(process, pointer, 3, info, 32, returned) == 0 then
            local base, size = tonumber(info[0]), tonumber(info[2])
            if base and size and size > 0 and base <= address then return base, size, true end
        end
        if tonumber(virtual_query(pointer, info, 48)) ~= 48 then return nil end
        local base, size = tonumber(info[0]), tonumber(info[3])
        if not base or not size or size <= 0 then return nil end
        -- state at +32: MEM_FREE 0x10000. Anything else here means region information is not
        -- available on this system; treat the region as one allocation.
        return base, size, info32[8] ~= 0x10000
    end

    -- One page: present in memory?, its protection, shared (mapped) or private.
    local page = ffi.new('uint64_t[2]')
    function a.page(address)
        page[0], page[1] = address - address % 4096, 0
        if working_set(process, page, 16) == 0 then return false end
        local attributes = tonumber(page[1] % 65536)
        if attributes % 2 ~= 1 then return false end
        return true, math.floor(attributes / 16) % 2048, attributes >= 32768
    end
    function a.readable_private(address)
        local present, protection, shared = a.page(address)
        return present and not shared and (protection == PAGE_READWRITE or protection == PAGE_READONLY)
    end

    a.buffer_size = FILE_CHUNK + 16
    a.buffer = ffi.new('uint8_t[?]', a.buffer_size)
    a.words = ffi.cast('uint32_t *', a.buffer)
    function a.read(address, size)
        if size <= 0 or size > a.buffer_size then return false end
        if read_memory(process, ffi.cast(cvoid, address), a.buffer, size, got) == 0 then return false end
        return tonumber(got[0]) == size
    end

    local cell = ffi.new('uint32_t[2]')
    function a.u32(address)
        if read_memory(process, ffi.cast(cvoid, address), cell, 4, got) == 0 then return nil end
        if tonumber(got[0]) ~= 4 then return nil end
        return tonumber(cell[0])
    end
    function a.u64(address)
        if read_memory(process, ffi.cast(cvoid, address), cell, 8, got) == 0 then return nil end
        if tonumber(got[0]) ~= 8 then return nil end
        return tonumber(cell[0]) + tonumber(cell[1]) * 4294967296
    end

    -- The only function in this file that changes game memory: 4 bytes, through the OS.
    local out = ffi.new('uint32_t[1]')
    function a.write_u32(address, bits)
        out[0] = bits
        if write_memory(process, ffi.cast(void, address), out, 4, got) == 0 then return false end
        return tonumber(got[0]) == 4
    end

    -- Changes the protection of the one page holding `address`. -> true when Windows accepted it.
    local old_protection = ffi.new('uint32_t[1]')
    function a.protect(address, protection)
        return virtual_protect(ffi.cast(void, address - address % 4096), 4096, protection, old_protection) ~= 0
    end

    -- f32 -> bit pattern, by copying the bytes of a float (no pointer aliasing).
    local float_cell, bits_cell = ffi.new('float[1]'), ffi.new('uint32_t[1]')
    function a.f32_bits(value)
        float_cell[0] = value
        ffi.copy(bits_cell, float_cell, 4)
        return tonumber(bits_cell[0])
    end

    function a.mkdir(path)
        return create_directory(path, nil) ~= 0 or get_last_error() == 183
    end

    function a.module(name)
        local handle = module_handle(name)
        if handle == nil then return nil end
        local path_buffer = ffi.new('char[1024]')
        local length = module_file_name(handle, path_buffer, 1024)
        return tonumber(ffi.cast('uintptr_t', handle)), length > 0 and ffi.string(path_buffer, length) or nil
    end
    function a.open(path)
        local handle = create_file(path, 0x80000000, 7, nil, 3, 0x08000000, nil)
        if handle == nil or tonumber(ffi.cast('intptr_t', handle)) == -1 then return nil end
        local size = ffi.new('int64_t[1]')
        if file_size(handle, size) == 0 then close_handle(handle); return nil end
        return handle, tonumber(size[0])
    end
    local file_got = ffi.new('uint32_t[1]')
    function a.read_file(handle)
        if read_file(handle, a.buffer, HASH_CHUNK, file_got, nil) == 0 then return nil end
        return tonumber(file_got[0])
    end
    function a.close(handle) close_handle(handle) end

    local B = 'bcrypt.dll'
    local open_algorithm = resolve(B, 'BCryptOpenAlgorithmProvider',
        'int32_t (*)(void **, const uint16_t *, const uint16_t *, uint32_t)')
    local close_algorithm = resolve(B, 'BCryptCloseAlgorithmProvider', 'int32_t (*)(void *, uint32_t)')
    local create_hash = resolve(B, 'BCryptCreateHash',
        'int32_t (*)(void *, void **, uint8_t *, uint32_t, uint8_t *, uint32_t, uint32_t)')
    local hash_data = resolve(B, 'BCryptHashData', 'int32_t (*)(void *, uint8_t *, uint32_t, uint32_t)')
    local finish_hash = resolve(B, 'BCryptFinishHash', 'int32_t (*)(void *, uint8_t *, uint32_t, uint32_t)')
    local destroy_hash = resolve(B, 'BCryptDestroyHash', 'int32_t (*)(void *)')
    local sha256_name = ffi.new('uint16_t[7]', { 83, 72, 65, 50, 53, 54, 0 })   -- L"SHA256"
    function a.sha256_begin()
        local algorithm, hash = ffi.new('void *[1]'), ffi.new('void *[1]')
        if open_algorithm(algorithm, sha256_name, nil, 0) ~= 0 then return nil end
        if create_hash(algorithm[0], hash, nil, 0, nil, 0, 0) ~= 0 then
            close_algorithm(algorithm[0], 0)
            return nil
        end
        return { algorithm = algorithm[0], hash = hash[0] }
    end
    function a.sha256_update(context, size) return hash_data(context.hash, a.buffer, size, 0) == 0 end
    function a.sha256_finish(context)
        local digest = ffi.new('uint8_t[32]')
        local ok = finish_hash(context.hash, digest, 32, 0) == 0
        destroy_hash(context.hash)
        close_algorithm(context.algorithm, 0)
        if not ok then return nil end
        local parts = {}
        for i = 0, 31 do parts[i + 1] = string.format('%02X', digest[i]) end
        return table.concat(parts)
    end

    -- keyboard: is the key down right now, and is the game the window in front?
    local own_process, window_owner = get_process_id(), ffi.new('uint32_t[1]')
    function a.key_down(vk) return key_state(vk) < 0 end
    function a.game_in_front()
        local window = foreground_window()
        if window == nil then return false end
        window_owner[0] = 0
        window_process(window, window_owner)
        return window_owner[0] == own_process
    end

    return a
end

-- ---------------------------------------------------------------- files
local out_dir = nil
local function ensure_out_dir()
    if out_dir then return out_dir end
    local base = os.getenv('LOCALAPPDATA')
    if not base or base == '' then return nil end
    local dir = base .. '\\' .. MOD.dir
    if A then pcall(A.mkdir, dir) end
    out_dir = dir
    return dir
end

-- Writes into our own folder; when that is impossible, into the loader's log folder.
local function write_file(name, text)
    local ok = pcall(function()
        local base = os.getenv('LOCALAPPDATA')
        local dir = ensure_out_dir()
        local handle = dir and io.open(dir .. '\\' .. name, 'wb')
        if not handle and base then
            handle = io.open(base .. '\\CowboyBingus\\Helldivers2\\Logs\\' .. MOD.dir .. '-' .. name, 'wb')
        end
        if not handle then return end
        handle:write(text)
        handle:close()
    end)
    return ok
end

local function read_file(name)
    local dir = ensure_out_dir()
    if not dir then return nil end
    local handle = io.open(dir .. '\\' .. name, 'rb')
    if not handle then return nil end
    local text = handle:read('*a')
    handle:close()
    return text
end

local function flush_log()
    log_dirty = false
    write_file(MOD.log, MOD.title .. ' v' .. MOD.version .. '\r\n'
        .. 'phase: ' .. state.phase .. '   errors: ' .. state.errors .. '\r\n\r\n'
        .. table.concat(log_lines, '\r\n') .. '\r\n')
end

-- ---------------------------------------------------------------- cooperative scheduling
local deadline = 0
local function pause()
    if A.now() >= deadline then coroutine.yield() end
end

-- ---------------------------------------------------------------- generated data
local BUILDS = {}                                    -- { label, exe, dll }
local SPECS, SPEC_BY_TYPE, SPEC_ORDER = {}, {}, {}   -- tables
local ITEMS, ITEM_BY_NAME = {}, {}                   -- index -> item; 'category:name' -> item
local FIELDS = {}                                    -- field key -> field (shared between items)
local RANGES, ALIASES = {}, {}
local field_count = 0

local function field_key(table_name, key, offset) return table_name .. '|' .. key .. '|' .. offset end

local function parse_data()
    local count = 0
    for line in DATA:gmatch('[^\n]+') do
        local kind = line:sub(1, 1)
        local f = {}
        for part in (line .. '|'):gmatch('([^|]*)|') do f[#f + 1] = part end
        if kind == 'V' then
            BUILDS[#BUILDS + 1] = { label = f[2], exe = f[3], dll = f[4] }
        elseif kind == 'T' then
            local spec = { name = f[2], type = tonumber(f[3], 16), shape = f[4],
                           stride = tonumber(f[5]), id_at = tonumber(f[6]), blocks = {} }
            SPECS[spec.name], SPEC_BY_TYPE[spec.type] = spec, spec
            SPEC_ORDER[#SPEC_ORDER + 1] = spec.name
        elseif kind == 'I' then
            local item = { index = tonumber(f[2]), category = f[3], name = f[4], entity = f[5],
                           stats = {}, stat_order = {} }
            ITEMS[item.index] = item
            ITEM_BY_NAME[item.category .. ':' .. item.name:lower()] = item
        elseif kind == 'F' then
            local item = ITEMS[tonumber(f[2])]
            local key = field_key(f[4], f[5], tonumber(f[6]))
            local field = FIELDS[key]
            if not field then
                field = { key = key, table = f[4], record = f[5], offset = tonumber(f[6]), storage = f[7],
                          stock = tonumber(f[8]), users = {} }
                FIELDS[key] = field
                field_count = field_count + 1
            end
            field.users[#field.users + 1] = item.name .. '.' .. f[3]
            if not item.stats[f[3]] then item.stat_order[#item.stat_order + 1] = f[3] end
            item.stats[f[3]] = { field = field, attachment = f[9] == 'A' }
        elseif kind == 'R' then
            RANGES[f[2]] = { min = tonumber(f[3]), max = tonumber(f[4]), integer = f[5] == '1' }
        elseif kind == 'A' then
            local targets = {}
            for name in f[4]:gmatch('[^,]+') do targets[#targets + 1] = name end
            ALIASES[f[2]] = { mode = f[3], targets = targets }
        end
        count = count + 1
        if count % 50 == 0 then pause() end
    end
    log('data: ' .. #BUILDS .. ' builds, ' .. #SPEC_ORDER .. ' tables, ' .. (#ITEMS + 1) .. ' items, '
        .. field_count .. ' fields')
end

-- ---------------------------------------------------------------- build gate
local build = { state = 'unchecked', modules = {} }

local function hash_module(name)
    local info = { name = name or 'helldivers2.exe' }
    local base, path = A.module(name)
    if not base or not path then info.note = 'not loaded'; return info end
    info.path = path
    local handle, size = A.open(path)
    if not handle then info.note = 'file could not be opened'; return info end
    info.file_size = size
    local context = A.sha256_begin()
    if not context then
        info.note = 'SHA-256 unavailable'
    else
        local total, ok = 0, true
        while true do
            local n = A.read_file(handle)
            if n == nil then ok = false break end
            if n == 0 then break end
            if not A.sha256_update(context, n) then ok = false break end
            total = total + n
            pause()
        end
        local digest = A.sha256_finish(context)
        if ok and digest and total == size then info.sha256 = digest
        else info.note = 'hashing failed after ' .. total .. ' bytes' end
    end
    A.close(handle)
    return info
end

-- Sets build.state to 'verified' only when BOTH files hash to the same known build.
local function check_build()
    local exe, dll = hash_module(nil), hash_module('game.dll')
    build.modules = { exe, dll }
    build.state, build.label = 'unknown', nil
    for _, known in ipairs(BUILDS) do
        if exe.sha256 and dll.sha256 and exe.sha256 == known.exe and dll.sha256 == known.dll then
            build.state, build.label = 'verified', known.label
        end
    end
    log('build: ' .. build.state .. (build.label and (' (' .. build.label .. ')') or '')
        .. ' exe=' .. tostring(exe.sha256 or exe.note) .. ' dll=' .. tostring(dll.sha256 or dll.note))
end

-- ---------------------------------------------------------------- finding tables
local search = { passes = 0, allocations = 0, seconds = 0, slowest_query = 0, slowest_at = 0 }

local function valid_block(block)
    return A.u32(block.address) == LDLD and A.u32(block.address + 4) == 1
        and A.u32(block.address + 8) == block.type and A.u32(block.address + 12) == block.size
end

-- Follows a chain of back-to-back blocks from `address`; keeps the blocks of wanted tables.
local function walk(address, origin, found)
    local steps = 0
    while steps < 200000 do
        if A.u32(address) ~= LDLD or A.u32(address + 4) ~= 1 then return end
        local kind, size = A.u32(address + 8), A.u32(address + 12)
        if not kind or kind == 0 or not size or size == 0 or size > MAX_BLOCK then return end
        local spec = SPEC_BY_TYPE[kind]
        if spec and not found[address] then
            found[address] = { address = address, type = kind, size = size, spec = spec,
                               origin = steps == 0 and origin or 'chain' }
        end
        steps = steps + 1
        local after, next_address = address + 24 + size, nil
        for skip = 0, 16, 4 do
            if A.u32(after + skip) == LDLD and A.u32(after + skip + 4) == 1 then
                next_address = after + skip
                break
            end
        end
        if not next_address then return end
        address = next_address
        pause()
    end
end

-- One pass over the allocations of the process: is there a table at the start of each?
-- (In-game recon: every table we use sits there or in the chain behind one.)
local function find_tables()
    local started, found = A.now(), {}
    search.allocations = 0
    local cursor = ADDRESS_START
    while cursor < ADDRESS_END do
        local t0 = A.now()
        local base, size, allocated = A.allocation(cursor)
        local cost = A.now() - t0
        if cost > search.slowest_query then search.slowest_query, search.slowest_at = cost, cursor end
        if not base then break end
        if allocated then
            search.allocations = search.allocations + 1
            if A.readable_private(base) then
                if A.u32(base) == LDLD and A.u32(base + 4) == 1 then
                    walk(base, 'allocation+0', found)
                elseif A.u32(base + 4) == LDLD and A.u32(base + 8) == 1 then
                    walk(base + 4, 'allocation+4', found)
                end
            end
        end
        local next_cursor = base + size
        if next_cursor <= cursor then next_cursor = cursor + 4096 end
        cursor = next_cursor
        pause()
    end
    -- merge: keep parsed blocks that are still there, add new ones, drop the rest
    for _, name in ipairs(SPEC_ORDER) do
        local spec, kept = SPECS[name], {}
        for _, block in ipairs(spec.blocks) do
            if found[block.address] and found[block.address].size == block.size then
                kept[#kept + 1] = block
                found[block.address] = nil
            end
        end
        spec.blocks = kept
    end
    for _, block in pairs(found) do
        block.spec.blocks[#block.spec.blocks + 1] = block
    end
    for _, name in ipairs(SPEC_ORDER) do
        table.sort(SPECS[name].blocks, function(x, y) return x.address < y.address end)
    end
    search.passes = search.passes + 1
    search.seconds = A.now() - started
    state.passes = search.passes
end

-- Keyed table: buckets (u64 entity, u32 record index, u32 0), twice as many as entities, then
-- fixed-size records. The bucket count is derived from the content, never assumed.
local function parse_keyed(block)
    local payload, size, stride = block.address + 24, block.size, block.spec.stride
    local limit = math.floor(size / (16 + stride / 2)) + 4
    local count, live, top, fits = 0, 0, -1, {}
    local offset, stop = 0, false
    while not stop and offset + 16 <= size and count <= limit do
        local want = math.min(8192, size - offset)
        want = want - want % 16
        if want < 16 or not A.read(payload + offset, want) then break end
        local w = A.words
        for k = 0, want / 16 - 1 do
            local lo, hi, index, pad = w[k * 4], w[k * 4 + 1], w[k * 4 + 2], w[k * 4 + 3]
            if pad ~= 0 or index > 1000000 or count > limit then stop = true break end
            count = count + 1
            if lo ~= 0 or hi ~= 0 then
                live = live + 1
                if index > top then top = index end
            end
            local rest = size - count * 16
            if count == 2 * live and rest > 0 and rest % stride < 8 then
                local records = (rest - rest % stride) / stride
                if records > top and records <= live + 2 then
                    fits[#fits + 1] = { buckets = count, records = records }
                end
            end
        end
        offset = offset + want
        pause()
    end
    if #fits ~= 1 then return nil, #fits .. ' bucket layouts fit (need exactly 1)' end
    local fit, index = fits[1], {}
    offset = 0
    while offset < fit.buckets * 16 do
        local want = math.min(8192, fit.buckets * 16 - offset)
        if not A.read(payload + offset, want) then return nil, 'bucket array unreadable' end
        local w = A.words
        for k = 0, want / 16 - 1 do
            local lo, hi = w[k * 4], w[k * 4 + 1]
            if lo ~= 0 or hi ~= 0 then
                local key = string.format('%08X%08X', hi, lo)
                if index[key] == nil then
                    local record = w[k * 4 + 2]
                    if record >= fit.records then return nil, 'record index out of range' end
                    index[key] = record
                end
            end
        end
        offset = offset + want
        pause()
    end
    block.records_at, block.index, block.count = payload + fit.buckets * 16, index, fit.records
    block.limit = payload + size
    return true
end

-- Row table: DLArray (u64 absolute pointer in memory, u64 count), then rows carrying a u32 id.
local function parse_rows(block)
    local payload, size, stride = block.address + 24, block.size, block.spec.stride
    local pointer, count = A.u64(payload), A.u64(payload + 8)
    if not pointer or not count then return nil, 'array head unreadable' end
    local rows_at
    if pointer < size then rows_at = payload + pointer
    elseif pointer >= payload and pointer < payload + size then rows_at = pointer
    else return nil, 'rows are outside the block' end
    if count == 0 or (rows_at - payload) + count * stride > size then
        return nil, 'rows do not fit (count ' .. count .. ')'
    end
    local index = {}
    local per_read = math.max(1, math.floor(FILE_CHUNK / stride))
    local row = 0
    while row < count do
        local n = math.min(per_read, count - row)
        if not A.read(rows_at + row * stride, n * stride) then return nil, 'rows unreadable' end
        local bytes = A.buffer
        for k = 0, n - 1 do
            local at = k * stride + block.spec.id_at
            local id = bytes[at] + bytes[at + 1] * 256 + bytes[at + 2] * 65536 + bytes[at + 3] * 16777216
            if index[id] == nil then index[id] = row + k end
        end
        row = row + n
        pause()
    end
    block.records_at, block.index, block.count = rows_at, index, count
    block.limit = payload + size
    return true
end

local function parse_block(block)
    if block.index or block.problem then return block.index ~= nil end
    state.step = 'reading table ' .. block.spec.name
    local ok, why
    if block.spec.shape == 'K' then ok, why = parse_keyed(block) else ok, why = parse_rows(block) end
    if not ok then
        block.problem = why
        log(block.spec.name .. ' at ' .. hex(block.address) .. ' cannot be parsed: ' .. tostring(why))
    end
    return ok == true
end

-- Address of `field` in `block`, or nil when the record is not in this table.
local function field_address(block, field)
    local key = field.record
    if block.spec.shape == 'R' then key = tonumber(key) end
    local record = block.index[key]
    if record == nil then return nil end
    local address = block.records_at + record * block.spec.stride + field.offset
    if address < block.address + 24 or address + 4 > block.limit then return nil end
    return address
end

local function read_field(address, storage)
    local bits = A.u32(address)
    if bits == nil then return nil end
    if storage == 'f32' then return bits_to_f32(bits) end
    if storage == 'i32' and bits >= 2147483648 then return bits - 4294967296 end
    return bits
end

-- value -> bit pattern, or nil when it cannot be represented exactly as intended
local function encode(value, storage)
    if storage == 'f32' then
        local bits = A.f32_bits(value)
        if not close_enough(bits_to_f32(bits), value) then return nil end   -- encoder vs decoder
        return bits
    end
    if value ~= math.floor(value) then return nil end
    if storage == 'i32' then
        if value < -2147483648 or value > 2147483647 then return nil end
        if value < 0 then return value + 4294967296 end
        return value
    end
    if value < 0 or value > 4294967295 then return nil end
    return value
end

