--   menu key (F9)   open / close            Left / Right   category, or change the value
--   Up / Down       move                    Tab            item list <-> value list
--   PageUp / Down   move ten                Shift          ten times the step
--   Delete          back to the game's value
-- A change is an entry of `overrides` (the same path the API uses): it is applied by the engine like a
-- config line, wins over config.txt for that value, and is kept in menu.txt.
local MENU_FILE = 'menu.txt'
local VK = { UP = 0x26, DOWN = 0x28, LEFT = 0x25, RIGHT = 0x27, TAB = 0x09, DELETE = 0x2E, PAGE_UP = 0x21,
             PAGE_DOWN = 0x22, SHIFT = 0x10 }
local MENU_CATEGORIES = { 'weapon', 'throwable', 'stratagem_weapon', 'stratagem', 'backpack', 'shield', 'vehicle' }
local MENU_ROWS = 20
local MENU_FONTS = { 'core/performance_hud/debug', 'core/editor_slave/gui/arial', 'gui/fonts/arial' }
local menu = { open = false, state = 'closed', tab = 1, focus = 'items', item = {}, stat = {}, keys = {},
               toggle_down = false, loaded = false }

local function menu_key_of(item, stat) return item.category .. ':' .. item.name:lower() .. ':' .. stat end

-- The engine's functions are native: a wrong argument can close the game instead of raising a Lua error
-- (v0.15.0 in game: F9 closed the game, and nothing in the log said where). So the first time each
-- engine call is about to be made, a line goes to the log file and is written out at once.
local menu_trail = {}
local function menu_step(name)
    if menu_trail[name] then return end
    menu_trail[name] = true
    log('menu: about to use ' .. name)
    flush_log()
end

-- menu.txt: the config format, written by the menu only
local function menu_load()
    menu.loaded = true
    local text = read_file(MENU_FILE)
    local section = nil
    for raw in ((text or '') .. '\n'):gmatch('([^\n]*)\n') do
        local line = trim((raw:gsub('#.*$', ''):gsub('\r', '')))
        local category, item = line:match('^%[%s*([%w_]+)%s*:%s*(.-)%s*%]$')
        local key, value = line:match('^([^=]+)=(.*)$')
        if category then
            section = category:lower() .. ':' .. item:lower()
        elseif key and section then
            overrides[section .. ':' .. trim(key):lower()] = trim(value)
        end
    end
end
local function menu_save()
    local keys = {}
    for key in pairs(overrides) do keys[#keys + 1] = key end
    table.sort(keys)
    local L, last = { '# Written by the in-game menu. Values here win over config.txt. Delete the file to forget them.' }, nil
    for _, key in ipairs(keys) do
        local category, item, stat = key:match('^([^:]+):([^:]+):(.+)$')
        if category then
            if last ~= category .. ':' .. item then
                last = category .. ':' .. item
                L[#L + 1] = ''
                L[#L + 1] = '[' .. category .. ': ' .. item .. ']'
            end
            L[#L + 1] = stat .. ' = ' .. overrides[key]
        end
    end
    write_file(MENU_FILE, table.concat(L, '\r\n') .. '\r\n')
end

local function menu_lists()
    if menu.lists then return menu.lists end
    if ITEMS[0] == nil then return nil end                -- the built-in data is still being read
    local lists = {}
    for _, category in ipairs(MENU_CATEGORIES) do lists[category] = {} end
    for index = 0, #ITEMS do
        local item = ITEMS[index]
        if item and lists[item.category] and #item.stat_order > 0 then
            lists[item.category][#lists[item.category] + 1] = item
        end
    end
    for _, list in pairs(lists) do
        table.sort(list, function(x, y) return (x.display or x.name):lower() < (y.display or y.name):lower() end)
    end
    menu.lists = lists
    return lists
end

-- the value shown for a stat: the menu's own, else the game's. -> value, changed?
local function menu_value(item, stat)
    local expression = overrides[menu_key_of(item, stat)]
    return tonumber(expression) or item.stats[stat].field.stock, expression ~= nil
end

local function menu_change(item, stat, direction, big, now)
    local entry, range = item.stats[stat], RANGES[stat]
    if not range then return end
    local whole = range.integer or entry.field.storage ~= 'f32'
    local size = math.abs(entry.field.stock)
    local step = whole and 1 or (size >= 100 and 10 or (size >= 10 and 1 or 0.1))
    if big then step = step * 10 end
    local value = menu_value(item, stat) + direction * step
    if not whole then value = math.floor(value * 1000 + 0.5) / 1000 end
    if value < range.min then value = range.min end
    if value > range.max then value = range.max end
    if same_value(entry.field.storage, value, entry.field.stock) then
        overrides[menu_key_of(item, stat)] = nil
    else
        overrides[menu_key_of(item, stat)] = whole and string.format('%.0f', value) or tostring(value)
    end
    menu.dirty_at = now
end

-- true when the key was just pressed, and again while it is held
local function menu_pressed(name, now)
    local k = menu.keys[name]
    if not A.key_down(VK[name]) then
        menu.keys[name] = nil
        return false
    end
    if not k then
        menu.keys[name] = { since = now, last = now }
        return true
    end
    if now - k.since > 0.35 and now - k.last > 0.05 then
        k.last = now
        return true
    end
    return false
end

local function menu_start()
    local S = rawget(_G, 'stingray')
    if type(S) ~= 'table' or type(S.Application) ~= 'table' or type(S.World) ~= 'table' or type(S.Gui) ~= 'table' then
        return nil, 'the engine has no Gui here'
    end
    menu_step('Application.main_world()')
    local ok, world = pcall(S.Application.main_world)
    if not ok or world == nil then return nil, 'no world to draw in' end
    menu_step('World.create_screen_gui(world, "immediate")')
    local made, gui = pcall(S.World.create_screen_gui, world, 'immediate')
    if not made or gui == nil then return nil, 'the screen gui could not be created: ' .. tostring(gui) end
    menu.S, menu.world, menu.gui = S, world, gui
    if not menu.font then
        menu_step('Gui.text (font test)')
        for _, font in ipairs(MENU_FONTS) do
            if not menu.font and pcall(function()
                S.Gui.text(gui, ' ', font, 16, font, S.Vector2(0, 0), S.Color(0, 0, 0, 0))
            end) then menu.font = font end
        end
    end
    if not menu.font then return nil, 'no font could be used' end
    -- Draw order. In game (v0.15.1) the panel and the selection bars covered the text: the Gui does not
    -- draw in call order. A Vector3 position carries a layer in z; whether this build takes one is
    -- tried once, and without layers nothing is drawn that could cover text.
    if menu.layers == nil then
        menu_step('Gui.rect / Gui.text with a Vector3 position (layer)')
        menu.layers = pcall(function()
            S.Gui.rect(gui, S.Vector3(0, 0, 900), S.Vector2(1, 1), S.Color(0, 0, 0, 0))
            S.Gui.text(gui, ' ', menu.font, 16, menu.font, S.Vector3(0, 0, 902), S.Color(0, 0, 0, 0))
        end)
        log('menu: layers ' .. (menu.layers and 'available' or 'not available: drawn without panel and bars'))
    end
    return true
end

local function menu_close(now)
    menu.open, menu.state, menu.width = false, 'closed', nil
    if menu.S and menu.gui then
        menu_step('World.destroy_gui(world, gui)')
        pcall(menu.S.World.destroy_gui, menu.world, menu.gui)
    end
    menu.gui, menu.world = nil, nil
    if menu.dirty_at then
        menu.dirty_at = nil
        request_reload()
    end
    pcall(menu_save)
end

local function menu_input(now)
    local lists = menu_lists()
    if not lists or not A.game_in_front() then return end
    local category = MENU_CATEGORIES[menu.tab]
    local list = lists[category]
    local selected = math.min(menu.item[category] or 1, math.max(#list, 1))
    local item = list[selected]
    local big = A.key_down(VK.SHIFT)
    local function move(by)
        if menu.focus == 'items' then
            menu.item[category] = math.max(1, math.min(#list, selected + by))
        elseif item then
            local at = menu.stat[item] or 1
            menu.stat[item] = math.max(1, math.min(#item.stat_order, at + by))
        end
    end
    if menu_pressed('TAB', now) then menu.focus = menu.focus == 'items' and 'stats' or 'items' end
    if menu_pressed('UP', now) then move(-1) end
    if menu_pressed('DOWN', now) then move(1) end
    if menu_pressed('PAGE_UP', now) then move(-10) end
    if menu_pressed('PAGE_DOWN', now) then move(10) end
    local side = (menu_pressed('RIGHT', now) and 1 or 0) - (menu_pressed('LEFT', now) and 1 or 0)
    if side ~= 0 then
        if menu.focus == 'items' then
            menu.tab = (menu.tab - 1 + side) % #MENU_CATEGORIES + 1
        elseif item then
            menu_change(item, item.stat_order[menu.stat[item] or 1], side, big, now)
        end
    end
    if menu_pressed('DELETE', now) and menu.focus == 'stats' and item then
        overrides[menu_key_of(item, item.stat_order[menu.stat[item] or 1])] = nil
        menu.dirty_at = now
    end
    -- a change is handed to the engine when the keys have been quiet for a moment
    if menu.dirty_at and now - menu.dirty_at > 0.3 then
        menu.dirty_at = nil
        request_reload()
        pcall(menu_save)
    end
end

local function menu_draw()
    local S, gui = menu.S, menu.gui
    if not menu.width then
        menu.width, menu.height = 1920, 1080
        menu_step('Application.back_buffer_size()')
        local ok, w, h = pcall(S.Application.back_buffer_size)
        if ok and type(w) == 'number' and type(h) == 'number' and w >= 640 and h >= 360 then
            menu.width, menu.height = w, h
        end
        log('menu: screen ' .. tostring(menu.width) .. ' x ' .. tostring(menu.height))
    end
    local width, height = menu.width, menu.height
    local scale = height / 1080
    menu_step('Gui.rect / Gui.text (first frame)')
    local PANEL_W, PANEL_H = 1180, 664
    local left, bottom = (width - PANEL_W * scale) / 2, (height - PANEL_H * scale) / 2
    -- panel coordinates: x from the left edge, y from the TOP edge of the panel (the Gui's origin is bottom left)
    local layers = menu.layers
    -- layer 900: the panel, 901: bars on it, 902: text
    local function rect(x, y, w_, h_, a, r, g, b, layer)
        if not layers then return end
        S.Gui.rect(gui, S.Vector3(left + x * scale, bottom + (PANEL_H - y - h_) * scale, layer or 901),
                   S.Vector2(w_ * scale, h_ * scale), S.Color(a, r, g, b))
    end
    local function text(str, x, y, size, a, r, g, b)
        local px, py = left + x * scale, bottom + (PANEL_H - y - size) * scale
        S.Gui.text(gui, str, menu.font, size * scale, menu.font,
                   layers and S.Vector3(px, py, 902) or S.Vector2(px, py), S.Color(a, r, g, b))
    end
    rect(0, 0, PANEL_W, PANEL_H, 245, 8, 10, 14, 900)
    rect(0, 0, PANEL_W, 4, 255, 255, 214, 0)
    text('BALANCE YOUR OWN GAME   v' .. MOD.version, 20, 16, 24, 255, 255, 214, 0)
    text(config.menu_key .. ' close    Tab switch list    Arrows move / change    Shift x10    Del reset', 520, 22, 16,
         255, 210, 210, 210)
    local lists = menu_lists()
    if not lists then
        text('reading the built-in data ...', 20, 80, 18, 255, 220, 220, 220)
        return
    end
    -- categories
    local x = 20
    for n, category in ipairs(MENU_CATEGORIES) do
        local label = category .. ' ' .. #lists[category]
        local w_ = 18 + #label * 10
        if n == menu.tab then rect(x, 56, w_, 26, 255, 255, 214, 0) end
        if n ~= menu.tab then text(label, x + 9, 60, 17, 255, 255, 255, 255)
        elseif layers then text(label, x + 9, 60, 17, 255, 0, 0, 0)
        else text(label, x + 9, 60, 17, 255, 255, 214, 0) end
        x = x + w_ + 6
    end
    local category = MENU_CATEGORIES[menu.tab]
    local list = lists[category]
    local selected = math.min(menu.item[category] or 1, math.max(#list, 1))
    local item = list[selected]
    -- items
    local first = math.max(1, math.min(selected - 9, #list - MENU_ROWS + 1))
    for row = 0, MENU_ROWS - 1 do
        local entry = list[first + row]
        if entry then
            local y = 96 + row * 26
            local here, focused = first + row == selected, first + row == selected and menu.focus == 'items'
            if here then
                rect(16, y, 400, 24, 255, focused and 255 or 70, focused and 214 or 70, focused and 0 or 60)
            end
            local label = (entry.display or entry.name):sub(1, 38)
            if not layers and here then label = '> ' .. label end
            if focused and layers then text(label, 24, y + 3, 17, 255, 0, 0, 0)
            elseif here and not layers then text(label, 24, y + 3, 17, 255, 255, 214, 0)
            else text(label, 24, y + 3, 17, 255, 255, 255, 255) end
        end
    end
    text(string.format('%d of %d', #list > 0 and selected or 0, #list), 24, 96 + MENU_ROWS * 26 + 4, 14, 255, 210, 210, 210)
    -- values of the selected item
    if item then
        text(item.display and (item.name .. '   (name in config.txt)') or '', 444, 96 - 22, 15, 255, 210, 210, 210)
        text('value', 780, 96 - 22, 15, 255, 210, 210, 210)
        text('game', 960, 96 - 22, 15, 255, 210, 210, 210)
        local at = math.min(menu.stat[item] or 1, #item.stat_order)
        local top = math.max(1, math.min(at - 9, #item.stat_order - MENU_ROWS + 1))
        for row = 0, MENU_ROWS - 1 do
            local stat = item.stat_order[top + row]
            if stat then
                local y = 96 + row * 26
                local value, changed = menu_value(item, stat)
                local field = item.stats[stat].field
                local here = top + row == at
                local focused = here and menu.focus == 'stats'
                if here then
                    rect(436, y, 728, 24, 255, focused and 255 or 70, focused and 214 or 70, focused and 0 or 60)
                end
                local dark = focused and layers
                local c = dark and 0 or 255
                local name = stat:sub(1, 36)
                if not layers and here then name = '> ' .. name end
                if focused and not layers then text(name, 444, y + 3, 17, 255, 255, 214, 0)
                else text(name, 444, y + 3, 17, 255, c, c, c) end
                if changed and not dark then
                    text(show(value, field.storage), 780, y + 3, 17, 255, 255, 214, 0)
                else
                    text(show(value, field.storage) .. (changed and '  *' or ''), 780, y + 3, 17, 255, c, c, c)
                end
                text(show(field.stock, field.storage), 960, y + 3, 17, 255, dark and 0 or 210, dark and 0 or 210,
                     dark and 0 or 210)
            end
        end
        text(string.format('%d of %d', at, #item.stat_order), 444, 96 + MENU_ROWS * 26 + 4, 14, 255, 210, 210, 210)
    end
    text(tostring(state.verdict or ''):sub(1, 120), 20, PANEL_H - 26, 14, 255, 210, 210, 210)
    if not menu_trail.drawn then
        menu_trail.drawn = true
        log('menu: first frame drawn')
        flush_log()
    end
end

-- once per frame
local function menu_tick()
    if not menu.loaded then pcall(menu_load) end
    local down = A.key_down(config.menu_vk)
    local toggled = down and not menu.toggle_down
    menu.toggle_down = down
    if toggled and not A.game_in_front() then toggled = false end
    local now = A.now()
    if toggled then
        if menu.open then
            menu_close(now)
        else
            local ok, started, why = pcall(menu_start)
            if ok and started then
                menu.open, menu.state = true, 'open'
            else
                menu.state = 'failed: ' .. tostring(why or started)
                log('menu: ' .. menu.state)
            end
        end
    end
    if not menu.open then return end
    local ok, why = pcall(function()
        menu_input(now)
        menu_draw()
    end)
    if not ok then
        log('menu: closed after an error: ' .. tostring(why))
        menu_close(now)
        menu.state = 'failed: ' .. tostring(why)
    end
end


local function tick()
    state.frame = state.frame + 1
    if state.frame < START_FRAME then return end
    menu_tick()
    -- the reload key: one key-state read per frame; the window is only checked on a press
    local down = A.key_down(config.reload_vk)
    if down and not key_was_down and A.game_in_front() then
        local pressed_at = A.now()
        if pressed_at - last_key_reload >= RELOAD_DEBOUNCE then
            last_key_reload = pressed_at
            log('reload key pressed')
            request_reload()
        end
    end
    key_was_down = down
    if state.frame % STEP_EVERY ~= 0 then return end
    local now = A.now()
    if config.auto_reload > 0 and now >= wake.config_check_at and build.state == 'verified' then
        wake.config_check_at = now + config.auto_reload
        local text = read_file(MOD.config)
        if text ~= nil and text ~= config.text then
            log('config.txt changed on disk')
            request_reload()
        end
    end
    if now < wake.at then return end
    if not worker then worker = coroutine.create(worker_main) end
    deadline = now + FRAME_BUDGET
    local ok, why = coroutine.resume(worker)
    local cost = A.now() - now
    state.busy_frames, state.busy_seconds = state.busy_frames + 1, state.busy_seconds + cost
    if cost > state.worst_frame then state.worst_frame, state.worst_step = cost, tostring(state.step) end
    if not ok then
        state.errors = state.errors + 1
        log('worker failed: ' .. tostring(why))
        worker = nil
        if state.errors >= 5 then
            state.phase, state.failure = 'gave_up', 'too many errors, last: ' .. tostring(why)
            state.retired = true
            write_status(true)
        else
            wake.at = A.now() + 5
            write_status(true)
        end
    end
end

-- ---------------------------------------------------------------- API (for a future UI)
-- Read access to everything the engine knows, and a way to change values without the file.
state.api = {
    version = 1,
    categories = function()
        local seen, list = {}, {}
        for index = 0, #ITEMS do
            local item = ITEMS[index]
            if item and not seen[item.category] then seen[item.category] = true; list[#list + 1] = item.category end
        end
        return list
    end,
    items = function(category)
        local list = {}
        for index = 0, #ITEMS do
            local item = ITEMS[index]
            if item and item.category == category then list[#list + 1] = item.name end
        end
        return list
    end,
    -- -> list of { id, game, current, min, max, integer, editable, shared_with }
    stats = function(category, name)
        local item = ITEM_BY_NAME[tostring(category) .. ':' .. tostring(name):lower()]
        if not item then return nil end
        local list = {}
        for _, stat in ipairs(item.stat_order) do
            local entry, range = item.stats[stat], RANGES[stat]
            local want = desired[entry.field.key]
            list[#list + 1] = { id = stat, game = entry.field.stock, current = want and want.value or entry.field.stock,
                                min = range.min, max = range.max, integer = range.integer,
                                editable = not entry.attachment, shared_with = #entry.field.users - 1 }
        end
        return list
    end,
    -- expression: '120', '150%', '+15', or nil to drop the override
    set = function(category, name, stat, expression)
        overrides[tostring(category):lower() .. ':' .. tostring(name):lower() .. ':' .. tostring(stat):lower()] =
            expression ~= nil and tostring(expression) or nil
        request_reload()
    end,
    reload = request_reload,
    verdict = function() return state.verdict end,
}

