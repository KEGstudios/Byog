local function parse_bool(text)
    text = text:lower()
    if text == 'true' or text == 'yes' or text == 'on' or text == '1' then return true end
    if text == 'false' or text == 'no' or text == 'off' or text == '0' then return false end
    return nil
end

-- 'N', 'N%', '+N', '-N' applied to the game's value -> number, or nil + reason
local function evaluate(expression, stock)
    local text = expression:gsub('%s+', ''):gsub(',', '.')
    local percent = text:match('^([%d%.]+)%%$')
    if percent then
        local n = tonumber(percent)
        if not n then return nil, 'not a number' end
        return stock * n / 100
    end
    local sign, amount = text:match('^([%+%-])([%d%.]+)$')
    if sign then
        local n = tonumber(amount)
        if not n then return nil, 'not a number' end
        if sign == '+' then return stock + n end
        return stock - n
    end
    local n = text:match('^[%d%.]+$') and tonumber(text)
    if not n then return nil, 'not a number (use 120, 150%, +15 or -5)' end
    return n
end

-- Turns one request (category, item, stat, expression) into field targets, or rejects it.
local function get_field(table_name, record, offset, storage, stock)
    local key = field_key(table_name, record, offset)
    local field = FIELDS[key]
    if not field then
        field = { key = key, table = table_name, record = record, offset = offset, storage = storage,
                  stock = stock, users = {} }
        FIELDS[key] = field
    end
    return field
end

-- With "own bullet", a stat of the shared projectile / damage row is set on the weapon's own row instead.
-- -> the field to write, and whether it was redirected
local function own_row_field(item, field)
    local t = item.active_takeover or item.takeover
    local source, new_row = nil, nil
    if field.table == 'ProjectileSettings' and field.record == tostring(t.src_projectile) then
        source, new_row = t.src_projectile, t.new_projectile
    elseif field.table == 'DamageSettings' and field.record == tostring(t.src_damage) then
        source, new_row = t.src_damage, t.new_damage
    end
    if not new_row then return field, false end
    local own_field
    if t.fresh then
        -- a row of our own starts as a copy of the weapon's row
        own_field = get_field(own_name(field.table), string.format('%.0f', new_row), field.offset, 'u32',
                              hex_word(ROWS[field.table .. '|' .. source], field.offset))
    else
        own_field = get_field(field.table, tostring(new_row), field.offset, 'u32',
                              hex_word(ROWS[field.table .. '|' .. new_row], field.offset))
    end
    own_field.exact = true
    return own_field, true
end

-- With an explosion of its own, a stat of the shared explosion row or of its damage row is set on the
-- item's own rows instead. -> the field to write and its group, or nil
local function own_blast_field(item, field)
    for _, a in ipairs(item.active_blasts or {}) do
        local own_field = nil
        if a.new_explosion and field.table == 'ExplosionSettings' and field.record == tostring(a.blast.explosion) then
            own_field = get_field('ExplosionSettings', tostring(a.new_explosion), field.offset, 'u32',
                                  hex_word(ROWS['ExplosionSettings|' .. a.new_explosion], field.offset))
        elseif a.own_damage and field.table == 'DamageSettings' and field.record == tostring(a.blast.damage) then
            own_field = get_field(own_name('DamageSettings'), string.format('%.0f', a.new_damage), field.offset, 'u32',
                                  hex_word(ROWS['DamageSettings|' .. a.blast.damage], field.offset))
        end
        if own_field then
            own_field.exact = true
            return own_field, a.group
        end
    end
    return nil
end

-- `blast_from = <item>`: this item explodes like that one. The value is not a number but the name of
-- another item (ids change between builds, names do not): its explosion row id is written into the
-- weapon's own projectile row, or into a throwable's own component record. The explosion itself stays
-- the source item's: changing the source's blast changes both.
local BLAST_ON_IMPACT = 144      -- ProjectileInfo.explosion_type_on_impact
local function resolve_blast_from(request, item, own_bullet)
    local source, wanted = nil, trim(request.expression):lower()
    for _, category in ipairs({ 'weapon', 'throwable', 'stratagem_weapon' }) do
        source = source or ITEM_BY_NAME[category .. ':' .. wanted]
    end
    if not source or not source.blasts then
        request.status, request.reason = 'rejected', 'blast_from takes the name of an item that explodes (see catalog.txt)'
        return
    end
    local explosion = source.blasts[1].explosion
    request.targets = {}
    local function target(field, stock)
        field.exact = true
        request.targets[#request.targets + 1] = { stat = 'blast_from', field = field, value = explosion,
            text = source.name .. ' (explosion row ' .. explosion .. ')', was_text = 'explosion row ' .. stock, own = true }
    end
    if item.takeover then
        local t = own_bullet[item] and own_bullet[item].takeover
        if not (t and t.fresh) then
            request.status, request.reason = 'rejected', 'blast_from needs the weapon\'s own projectile row (own_rows = auto)'
            return
        end
        local stock = hex_word(ROWS['ProjectileSettings|' .. t.src_projectile], BLAST_ON_IMPACT)
        target(get_field(own_name('ProjectileSettings'), string.format('%.0f', t.new_projectile), BLAST_ON_IMPACT, 'u32',
                         stock), stock)
    elseif item.blasts and item.blasts[1].kind == 'C' then
        for _, s in ipairs(item.blasts[1].switches) do
            target(get_field(s.table, item.entity, s.offset, 'u32', item.blasts[1].explosion), item.blasts[1].explosion)
            request.targets[#request.targets].own = nil      -- the item's own record: a plain value
        end
    else
        request.status, request.reason = 'rejected', 'blast_from is not possible for this item'
        return
    end
    request.status = 'accepted'
end

local function resolve_request(request, own_bullet)
    local item = ITEM_BY_NAME[request.category .. ':' .. request.item:lower()]
    if not item then
        request.status, request.reason = 'rejected', 'unknown ' .. request.category .. ' (see catalog.txt)'
        return
    end
    local stats, nonzero = { request.stat }, false
    local alias = ALIASES[request.stat]
    if alias then stats, nonzero = alias.targets, alias.mode == 'nonzero' end
    if request.stat == 'blast_from' then return resolve_blast_from(request, item, own_bullet) end
    request.targets = {}
    for _, stat in ipairs(stats) do
        local entry, range = item.stats[stat], RANGES[stat]
        if entry and range and not (nonzero and entry.field.stock == 0) then
            local value, why = evaluate(request.expression, entry.field.stock)
            if not value then request.status, request.reason = 'rejected', why return end
            if range.integer or entry.field.storage ~= 'f32' then value = math.floor(value + 0.5) end
            if value ~= value or value < range.min or value > range.max then
                request.status = 'rejected'
                request.reason = string.format('%s = %s is outside the allowed range %s .. %s', stat,
                    show(value, 'f32'), show(range.min, 'f32'), show(range.max, 'f32'))
                return
            end
            local bits = encode(value, entry.field.storage)
            if bits == nil then
                request.status, request.reason = 'rejected', stat .. ' = ' .. tostring(value) .. ' cannot be stored'
                return
            end
            local target = { stat = stat, field = entry.field, value = value,
                             text = show(value, entry.field.storage), attachment = entry.attachment }
            local base = entry.attachment and config.own_rows and item.magazine and item.magazine.base[stat]
            if base then
                -- the value goes into the weapon's own record; the attachment's is switched off (build_desired)
                target.field = get_field(base.table, base.record, base.offset, base.storage, base.stock)
                if #target.field.users == 0 then target.field.users[1] = item.name .. '.' .. stat end
                target.was_text, target.magazine, target.attachment = show(entry.field.stock, entry.field.storage), item, nil
            end
            if own_bullet[item] then
                local field, redirected = own_row_field(item, entry.field)
                if redirected then
                    -- the own row is written as raw words; keep the readable numbers for the report
                    target.field, target.value = field, bits
                    target.was_text, target.own = show(entry.field.stock, entry.field.storage), true
                end
            end
            if not target.own then
                local field, group = own_blast_field(item, entry.field)
                if field then
                    -- the own rows are written as raw words; keep the readable numbers for the report
                    target.field, target.value, target.group = field, bits, group
                    target.was_text, target.own = show(entry.field.stock, entry.field.storage), true
                end
            end
            request.targets[#request.targets + 1] = target
        elseif not alias then
            request.status = 'rejected'
            request.reason = 'this ' .. request.category .. ' has no stat "' .. stat .. '" (see catalog.txt)'
            return
        end
    end
    if #request.targets == 0 then
        request.status, request.reason = 'rejected', 'nothing to set: no "' .. request.stat .. '" value on this item'
        return
    end
    request.status = 'accepted'
end

-- Is `stat` of `item` a value of blast `b`: in its explosion row, in the explosion's damage row?
local function blast_touch(item, b, stat)
    local stats, in_row, in_damage = { stat }, false, false
    if ALIASES[stat] then stats = ALIASES[stat].targets end
    for _, name in ipairs(stats) do
        local field = item.stats[name] and item.stats[name].field
        if field and field.table == 'ExplosionSettings' and field.record == tostring(b.explosion) then in_row = true end
        if field and b.damage ~= 0 and field.table == 'DamageSettings' and field.record == tostring(b.damage) then
            in_damage = true
        end
    end
    return in_row, in_damage
end

-- Does `stat` of `item` live in the projectile / damage row the weapon shares with others?
local function touches_shared_rows(item, stat)
    if stat == 'blast_from' then return true end        -- written into the weapon's own projectile row
    local t, stats = item.takeover, { stat }
    if ALIASES[stat] then stats = ALIASES[stat].targets end
    for _, name in ipairs(stats) do
        local field = item.stats[name] and item.stats[name].field
        if field and ((field.table == 'ProjectileSettings' and field.record == tostring(t.src_projectile))
            or (field.table == 'DamageSettings' and field.record == tostring(t.src_damage))) then
            return true
        end
    end
    for _, b in ipairs(item.blasts or {}) do
        if b.kind == 'P' and not b.own then
            -- an explosion row of its own is reached through a projectile row of its own
            local in_row, in_damage = blast_touch(item, b, stat)
            if in_row or in_damage then return true end
        end
    end
    return false
end

-- Parses the config text and the API overrides into `desired`.
local function build_desired(text)
    config.requests, config.problems = {}, {}
    config.enabled, config.reload_key, config.reload_vk = true, 'F10', 0x79
    config.menu_key, config.menu_vk = 'F9', 0x78
    config.auto_reload, config.rescan, config.probe, config.own_rows = 0, DEFAULT_RESCAN_SECONDS, false, true
    config.census, config.canary, config.dump_globals, config.ui_probe = false, false, false, false
    local section, line_number = nil, 0
    local by_stat = {}   -- 'category:item:stat' -> request (a later line replaces an earlier one)
    for raw in ((text or '') .. '\n'):gmatch('([^\n]*)\n') do
        line_number = line_number + 1
        local line = trim((raw:gsub('#.*$', ''):gsub('\r', '')))
        if line ~= '' then
            local header = line:match('^%[(.-)%]$')
            local key, value = line:match('^([^=]+)=(.*)$')
            if header then
                local category, item = header:match('^%s*([%w_]+)%s*:%s*(.-)%s*$')
                if trim(header):lower() == 'settings' then
                    section = { settings = true }
                elseif category and item ~= '' then
                    section = { category = category:lower(), item = item }
                else
                    section = nil
                    config.problems[#config.problems + 1] = 'line ' .. line_number .. ': cannot read section "' .. line .. '"'
                end
            elseif key and section then
                key, value = trim(key):lower(), trim(value)
                if section.settings then
                    if key == 'enabled' and parse_bool(value) ~= nil then
                        config.enabled = parse_bool(value)
                    elseif key == 'reload_key' and value:upper():match('^F%d%d?$')
                        and tonumber(value:sub(2)) >= 1 and tonumber(value:sub(2)) <= 12 then
                        config.reload_key = value:upper()
                        config.reload_vk = 0x6F + tonumber(value:sub(2))
                    elseif key == 'menu_key' and value:upper():match('^F%d%d?$')
                        and tonumber(value:sub(2)) >= 1 and tonumber(value:sub(2)) <= 12 then
                        config.menu_key = value:upper()
                        config.menu_vk = 0x6F + tonumber(value:sub(2))
                    elseif key == 'auto_reload_seconds' and tonumber(value) and tonumber(value) >= 0 then
                        config.auto_reload = tonumber(value)
                    elseif key == 'rescan_seconds' and tonumber(value) and tonumber(value) >= 0 then
                        config.rescan = tonumber(value)
                    elseif key == 'probe' and parse_bool(value) ~= nil then
                        config.probe = parse_bool(value)
                    elseif key == 'census' and parse_bool(value) ~= nil then
                        config.census = parse_bool(value)
                    elseif key == 'canary' and parse_bool(value) ~= nil then
                        config.canary = parse_bool(value)
                    elseif key == 'dump_globals' and parse_bool(value) ~= nil then
                        config.dump_globals = parse_bool(value)
                    elseif key == 'ui_probe' and (value:lower() == 'text' or parse_bool(value) ~= nil) then
                        config.ui_probe = value:lower() == 'text' and 'text' or parse_bool(value)
                    elseif key == 'own_rows' and (value:lower() == 'auto' or parse_bool(value) ~= nil) then
                        config.own_rows = value:lower() == 'auto' or parse_bool(value) == true
                    else
                        config.problems[#config.problems + 1] = 'line ' .. line_number .. ': unknown setting "' .. line .. '"'
                    end
                else
                    local request = { line = line_number, category = section.category, item = section.item,
                                      stat = key, expression = value, text = line }
                    by_stat[section.category .. ':' .. section.item:lower() .. ':' .. key] = request
                    config.requests[#config.requests + 1] = request
                end
            else
                config.problems[#config.problems + 1] = 'line ' .. line_number .. ': cannot read "' .. line .. '"'
            end
        end
    end
    for key, expression in pairs(overrides) do
        local category, item, stat = key:match('^([^:]+):([^:]+):(.+)$')
        local previous = by_stat[key]
        if previous then previous.status, previous.reason = 'replaced', 'replaced through the API' end
        local request = { line = 0, category = category, item = item, stat = stat, expression = expression,
                          text = stat .. ' = ' .. expression .. ' (API)' }
        by_stat[key] = request
        config.requests[#config.requests + 1] = request
    end
    -- a later line for the same item and stat replaces the earlier one
    for _, request in ipairs(config.requests) do
        local key = request.category .. ':' .. request.item:lower() .. ':' .. request.stat
        if not request.status and by_stat[key] ~= request then
            request.status, request.reason = 'replaced', 'a later line sets the same stat'
        end
    end
    desired = {}
    if not config.enabled then
        for _, request in ipairs(config.requests) do
            if not request.status then request.status, request.reason = 'off', 'enabled = false' end
        end
        return
    end
    -- "own_bullet = true" first: it decides where the other lines of that weapon go
    local own_bullet, declined = {}, {}
    -- brand-new damage and projectile ids in memory of our own; a failure is written into `request`
    local function fresh_rows(item, request)
        local t = item.takeover
        local damage_id, why = own_row(item, 'DamageSettings', t.src_damage)
        local id = nil
        if damage_id then id, why = own_row(item, 'ProjectileSettings', t.src_projectile, damage_id) end
        if not id then
            request.status, request.reason = 'rejected', 'new row ids are not possible: ' .. tostring(why)
            return nil
        end
        -- other rounds of the same weapon (tracers in a belt): a row of their own each, on the same damage row
        local rounds = {}
        for _, s in ipairs(item.switches or {}) do
            local stock = ROWS['ProjectileSettings|' .. s.projectile]
            if s.projectile ~= t.src_projectile and rounds[s.projectile] == nil and stock
                and hex_word(stock, OWN_DAMAGE_AT) == t.src_damage then
                rounds[s.projectile] = own_row(item, 'ProjectileSettings', s.projectile, damage_id, ':round' .. s.projectile)
                    or false
            end
        end
        return { base_projectile = t.base_projectile, src_projectile = t.src_projectile, new_projectile = id,
                 src_damage = t.src_damage, new_damage = damage_id, fresh = true, rounds = rounds }
    end
    for _, request in ipairs(config.requests) do
        if not request.status and request.stat == 'own_bullet' then
            local item = ITEM_BY_NAME[request.category .. ':' .. request.item:lower()]
            local fresh = trim(request.expression):lower() == 'new'
            local wanted = fresh or parse_bool(request.expression)
            if not item then
                request.status, request.reason = 'rejected', 'unknown ' .. request.category .. ' (see catalog.txt)'
            elseif wanted == nil then
                request.status, request.reason = 'rejected', 'own_bullet takes true, false or new'
            elseif not item.takeover then
                request.status, request.reason = 'rejected', 'own_bullet is not available for this weapon yet'
            elseif not wanted then
                request.status, request.reason = 'off', 'own_bullet = false'
            else
                local t = item.takeover
                if fresh then
                    t = fresh_rows(item, request)
                elseif t.new_projectile == 0 then
                    request.status = 'rejected'
                    request.reason = 'own_bullet = true needs a spare row, and none is assigned to this weapon; use own_bullet = new'
                end
                if not request.status then
                    request.status, request.targets, request.own_item, request.takeover = 'accepted', {}, item, t
                    item.active_takeover = t
                    own_bullet[item] = request
                end
            end
            -- an own_bullet line that did not take effect (false, or refused) is the user's word:
            -- such a weapon is not given rows automatically
            if item and request.status ~= 'accepted' then declined[item] = true end
        end
    end
    -- Automatic: a weapon whose shared projectile / damage values are changed gets rows of its own,
    -- so that the change reaches this weapon only.
    if config.own_rows then
        local automatic = {}
        for _, request in ipairs(config.requests) do
            local item = not request.status and ITEM_BY_NAME[request.category .. ':' .. request.item:lower()]
            if item and item.takeover and not own_bullet[item] and not declined[item]
                and touches_shared_rows(item, request.stat) then
                local auto = { line = request.line, category = request.category, item = request.item, stat = 'own_bullet',
                               expression = 'new', text = 'rows of its own (automatic)', automatic = true }
                local t = fresh_rows(item, auto)
                if t then
                    auto.status, auto.targets, auto.own_item, auto.takeover = 'accepted', {}, item, t
                    item.active_takeover = t
                    own_bullet[item] = auto
                else
                    declined[item] = true      -- said once; this weapon's values then go to the shared rows
                end
                automatic[#automatic + 1] = auto
            end
        end
        for _, auto in ipairs(automatic) do config.requests[#config.requests + 1] = auto end
    end
    -- Explosions of their own (automatic). A blast stat of an item whose explosion row is reached by
    -- something else gets a borrowed explosion row; a blast damage stat whose damage row is shared gets
    -- a new damage id. A weapon needs its own projectile row for the first (the pass above gives it).
    local blasts = {}
    for _, item in pairs(ITEMS) do item.active_blasts = nil end
    if config.own_rows then
        local notes, refused = {}, {}
        for _, request in ipairs(config.requests) do
            local item = not request.status and request.stat ~= 'own_bullet' and request.stat ~= 'blast_from'
                and ITEM_BY_NAME[request.category .. ':' .. request.item:lower()]
            for _, b in ipairs(item and not declined[item] and item.blasts or {}) do
                local in_row, in_damage = blast_touch(item, b, request.stat)
                local t = own_bullet[item] and own_bullet[item].takeover
                local same_damage = t and b.damage == t.src_damage     -- the round and its blast use one damage row
                local a = nil
                for _, active in ipairs(item.active_blasts or {}) do
                    if active.blast == b then a = active end
                end
                if (in_row or in_damage) and not a and not refused[b] then
                    local why = nil
                    if not b.own then
                        if b.kind == 'P' and not (t and t.fresh) then
                            why = 'the weapon has no projectile row of its own'
                        elseif config.canary then
                            why = 'the rows to borrow are in use by the canary test'
                        else
                            local id
                            id, why = spare_row(item.name .. ':' .. b.explosion, 'ExplosionSettings', b.explosion)
                            if id then a = { new_explosion = id } end
                        end
                    elseif in_damage and (b.shared_damage or same_damage) then
                        a = {}
                    end
                    local note = { line = request.line, category = request.category, item = request.item, stat = 'own_blast',
                                   expression = 'new', text = 'explosion of its own (automatic)', automatic = true }
                    if a then
                        a.blast, a.item, a.takeover, a.request = b, item, t, note
                        a.group = 'blast:' .. item.name .. ':' .. b.explosion
                        item.active_blasts = item.active_blasts or {}
                        item.active_blasts[#item.active_blasts + 1] = a
                        blasts[#blasts + 1] = a
                        note.status, note.targets, note.blast = 'accepted', {}, a
                        notes[#notes + 1] = note
                    elseif why then
                        refused[b] = true
                        note.status, note.reason = 'rejected', why .. '; its blast values go to the shared rows'
                        notes[#notes + 1] = note
                    end
                end
                -- the damage row: of its own when the explosion row is borrowed, or when a damage value is set
                if a and b.damage ~= 0 and not a.new_damage and (a.new_explosion or in_damage) then
                    if same_damage then
                        a.new_damage = t.new_damage
                    else
                        local id, why = own_row(item, 'DamageSettings', b.damage, nil, ':blast' .. b.explosion)
                        if id then a.new_damage, a.own_damage = id, true else a.problem = why end
                    end
                end
            end
        end
        for _, note in ipairs(notes) do config.requests[#config.requests + 1] = note end
    end
    for _, request in ipairs(config.requests) do
        if not request.status then resolve_request(request, own_bullet) end
    end
    -- A line that names one value wins over a shortcut that also covers it: with all_health = 300% and
    -- part_leg_left_health = 10 the leg gets 10. (In game, v0.12.0, the two lines rejected each other.)
    local direct = {}
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' and not ALIASES[request.stat] then
            for _, target in ipairs(request.targets) do
                direct[request.category .. ':' .. request.item:lower() .. ':' .. target.stat] = request.line
            end
        end
    end
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' and ALIASES[request.stat] then
            local kept = {}
            for _, target in ipairs(request.targets) do
                local line = direct[request.category .. ':' .. request.item:lower() .. ':' .. target.stat]
                if line then
                    request.yielded = (request.yielded and (request.yielded .. ', ') or '') .. target.stat
                        .. ' (line ' .. line .. ')'
                else
                    kept[#kept + 1] = target
                end
            end
            request.targets = kept
        end
    end
    -- shared values: different targets for the same field reject every request involved
    local claims = {}
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' then
            for _, target in ipairs(request.targets) do
                local claim = claims[target.field.key]
                if not claim then
                    claims[target.field.key] = { value = target.value, requests = { request }, field = target.field }
                else
                    claim.requests[#claim.requests + 1] = request
                    if not same_value(target.field.storage, claim.value, target.value) then claim.conflict = true end
                end
            end
        end
    end
    for _, claim in pairs(claims) do
        if claim.conflict then
            local lines = {}
            for _, request in ipairs(claim.requests) do lines[#lines + 1] = request.line end
            table.sort(lines)
            for _, request in ipairs(claim.requests) do
                request.status = 'rejected'
                request.reason = 'lines ' .. table.concat(lines, ', ')
                    .. ' ask for different values of the same shared value (' .. claim.field.table .. ' '
                    .. claim.field.record .. ' +' .. claim.field.offset .. ')'
            end
        end
    end
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' then
            for _, target in ipairs(request.targets) do
                local entry = desired[target.field.key]
                if not entry then
                    entry = { field = target.field, value = target.value, sources = {} }
                    desired[target.field.key] = entry
                end
                entry.sources[#entry.sources + 1] = request
                if target.own then entry.group, entry.order = target.group or request.item:lower(), 1 end
            end
        end
    end
    -- A value the game will cap: more magazines at the start than the weapon may carry (seen in game,
    -- v0.8.0: mags_start = 10 with mags_max left at 8 started with 8). Said on the line, never "fixed":
    -- one line changes one value.
    local wanted = {}
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' then
            for _, target in ipairs(request.targets) do
                wanted[request.category .. ':' .. request.item:lower() .. ':' .. target.stat] = { request = request, target = target }
            end
        end
    end
    for key, w in pairs(wanted) do
        if w.target.stat == 'mags_start' then
            local item = ITEM_BY_NAME[w.request.category .. ':' .. w.request.item:lower()]
            local max = wanted[(key:gsub('mags_start$', 'mags_max'))]
            local limit = max and tonumber(max.target.text) or (item.stats.mags_max and item.stats.mags_max.field.stock)
            local start = tonumber(w.target.text)
            if limit and start and start > limit then
                w.request.warning = string.format('mags_start %d is above mags_max %d: the game starts with %d. '
                    .. 'Set mags_max as well', start, limit, limit)
            end
        end
    end
    -- A vehicle part that outlasts the vehicle: damage to a part also goes to the main health (to_main),
    -- so a part whose health is above what the main health can pay for never breaks (seen in game,
    -- v0.11.0: a leg with 100000 health, the exosuit was destroyed first). Said on the line, not "fixed".
    local function effective(item_key, item, stat)
        local w = wanted[item_key .. ':' .. stat]
        if w then return tonumber(w.target.text) end
        return item.stats[stat] and item.stats[stat].field.stock
    end
    local function outlasts(item_key, item, part)
        local main, share = effective(item_key, item, 'health'), effective(item_key, item, 'part_' .. part .. '_to_main')
        local health = effective(item_key, item, 'part_' .. part .. '_health')
        if main and share and health and share > 0 and health * share > main then return health, main, share end
        return nil
    end
    for _, w in pairs(wanted) do
        local item_key = w.request.category .. ':' .. w.request.item:lower()
        local item = ITEM_BY_NAME[item_key]
        local part = w.target.stat:match('^part_(.+)_health$') or w.target.stat:match('^part_(.+)_to_main$')
        local parts = part and { part } or {}
        if w.target.stat == 'health' and w.request.category == 'vehicle' then
            for _, stat in ipairs(item.stat_order) do
                parts[#parts + 1] = stat:match('^part_(.+)_health$')
            end
        end
        for _, name in ipairs(parts) do
            local health, main, share = outlasts(item_key, item, name)
            if health and not w.request.warning then
                w.request.warning = string.format('part %s has %d health and passes %d%% of its damage on, the main health '
                    .. 'is %d: the vehicle is destroyed before this part breaks. Raise health, lower part_%s_to_main, or '
                    .. 'use all_health to scale everything together', name, health, share * 100, main, name)
            end
        end
    end
    -- Magazine values of a weapon's own. Where a default magazine attachment sets the magazine values,
    -- the attachment is shared by every weapon that carries it. Its run of magazine deltas is switched
    -- off (count 0 in the delta storage), and every weapon that carries this magazine by default gets
    -- the values in its own record: the config's for the weapon being changed, the attachment's stock
    -- values for the others. order 1 = the records, order 2 = the switch, as with own bullets.
    local magazines = {}
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' then
            for _, target in ipairs(request.targets) do
                if target.magazine then magazines[target.magazine.magazine.resource] = target.magazine.magazine end
            end
        end
    end
    for resource, magazine in pairs(magazines) do
        local group = 'magazine:' .. resource
        for _, item in ipairs(MAGAZINES[resource]) do
            for stat, base in pairs(item.magazine.base) do
                local field = get_field(base.table, base.record, base.offset, base.storage, base.stock)
                if #field.users == 0 then field.users[1] = item.name .. '.' .. stat end
                local entry = desired[field.key]
                if not entry then
                    entry = { field = field, value = item.stats[stat].field.stock, sources = {}, base = true }
                    desired[field.key] = entry
                end
                entry.group, entry.order = group, 1
            end
        end
        local switch = get_field('ComponentEntityDeltaStorage', 'components', magazine.run_at, 'u32', magazine.run_count)
        switch.exact = true
        desired[switch.key] = { field = switch, value = 0, sources = {}, base = true, group = group, order = 2 }
    end
    -- explosions of their own: order 1 = the borrowed row (a copy of the item's row, pointing at the
    -- damage row of its own), order 2 = the switches that make the item use it
    local function copy_explosion(source, target, damage, group)
        local from, to = ROWS['ExplosionSettings|' .. source], ROWS['ExplosionSettings|' .. target]
        local live = LIVE_WORDS.ExplosionSettings or {}
        for offset = 4, SPECS.ExplosionSettings.stride - 4, 4 do
            local field = get_field('ExplosionSettings', tostring(target), offset, 'u32', hex_word(to, offset))
            local value = hex_word(from, offset)
            if live[offset] then
                -- part of an array head: an address, only known in memory. Copied from the source row.
                field.exact, field.live = nil, get_field('ExplosionSettings', tostring(source), offset, 'u32', value)
            else
                field.exact, field.live = true, nil
                if offset == 4 and damage then value = damage end
            end
            local entry = desired[field.key]
            if not entry then
                entry = { field = field, value = value, sources = {}, base = true }
                desired[field.key] = entry
            end
            entry.group, entry.order = group, 1
        end
    end
    for _, a in ipairs(blasts) do
        local b = a.blast
        local function switch(field, value)
            field.exact = true
            desired[field.key] = { field = field, value = value, sources = { a.request }, base = true, group = a.group,
                                   order = 2, needs_index = (a.new_damage ~= nil or b.kind == 'P') or nil }
        end
        if a.new_explosion then
            copy_explosion(b.explosion, a.new_explosion, a.new_damage, a.group)
            for _, s in ipairs(b.switches) do
                if b.kind == 'P' then
                    switch(get_field(own_name('ProjectileSettings'), string.format('%.0f', a.takeover.new_projectile),
                                     s.offset, 'u32', b.explosion), a.new_explosion)
                else
                    switch(get_field(s.table, a.item.entity, s.offset, 'u32', b.explosion), a.new_explosion)
                end
            end
        elseif a.new_damage then
            switch(get_field('ExplosionSettings', tostring(b.explosion), 4, 'u32', b.damage), a.new_damage)
        end
    end
    -- canary (research): every row of the borrowing list becomes a copy of a harmless, very visible
    -- explosion. Anything in the game that uses one of these rows then shows that explosion instead.
    if config.canary and MARKER.ExplosionSettings then
        for _, id in ipairs(SPARE.ExplosionSettings or {}) do
            copy_explosion(MARKER.ExplosionSettings, id, nil, 'canary')
        end
    end
    -- own bullets: copy the weapon's round into the spare rows, then point the weapon at them.
    -- order 1 = the rows, order 2 = the switches (only thrown when every row field is in place).
    for item, request in pairs(own_bullet) do
        local t, group = request.takeover, item.name
        local function want(field, value, order)
            field.exact = true
            local entry = desired[field.key]
            if not entry then
                entry = { field = field, value = value, sources = { request }, base = true }
                desired[field.key] = entry
            end
            entry.group, entry.order = group, order
            if order == 2 and t.fresh then entry.needs_index = true end
        end
        local function copy_row(table_name, source, target, size, patch_at, patch_value)
            local from, to = ROWS[table_name .. '|' .. source], ROWS[table_name .. '|' .. target]
            for offset = 4, size - 4, 4 do
                local value = hex_word(from, offset)
                if offset == patch_at then value = patch_value end
                want(get_field(table_name, tostring(target), offset, 'u32', hex_word(to, offset)), value, 1)
            end
        end
        if t.fresh then
            -- the row of our own already is a copy; its damage row id is the one field we insist on
            want(get_field(own_name('ProjectileSettings'), string.format('%.0f', t.new_projectile), OWN_DAMAGE_AT, 'u32',
                           t.new_damage), t.new_damage, 1)
        else
            copy_row('ProjectileSettings', t.src_projectile, t.new_projectile, SPECS.ProjectileSettings.stride,
                     OWN_DAMAGE_AT, t.new_damage)
            copy_row('DamageSettings', t.src_damage, t.new_damage, SPECS.DamageSettings.stride, -1, 0)
        end
        if t.base_projectile then
            want(get_field('ProjectileWeaponComponentData', item.entity, 0, 'u32', t.base_projectile),
                 t.new_projectile, 2)
        end
        -- every other place of the item's own records that names a round (belt pattern, strike component)
        for _, s in ipairs(t.fresh and item.switches or {}) do
            local new = t.new_projectile
            if s.projectile ~= t.src_projectile then new = t.rounds and t.rounds[s.projectile] end
            if new then want(get_field(s.table, item.entity, s.offset, 'u32', s.projectile), new, 2) end
        end
        if item.ammo_delta then
            want(get_field('ComponentEntityDeltaStorage', 'data', item.ammo_delta.offset, 'u32',
                           item.ammo_delta.expected), t.new_projectile, 2)
        end
    end
end

