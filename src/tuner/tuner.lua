        add('census: ' .. census.state .. (census.note and (' (' .. census.note .. ')') or '')
            .. (census.bytes and string.format(', %.0f bytes swept', census.bytes) or '')
            .. (census.state == 'done' and ' -> CENSUS.txt' or ''))
    end
    for _, problem in ipairs(config.problems) do add('config problem: ' .. problem) end
    if own.state ~= 'unused' then
        add('')
        add('[own rows] ' .. own.state .. (own.note and (': ' .. own.note) or ''))
        if own.block then
            add('block ' .. hex(own.block) .. ' size ' .. OWN_SIZE)
            for _, name in ipairs(OWN_TABLES) do
                local t = own.tables[name]
                add(string.format('%s: game index %s, first new id %.0f, rows in use %d of %d', name, hex(t.index),
                                  t.first_id, t.count, OWN_CAPACITY))
            end
            for _, user in ipairs(own.order) do
                add(string.format('  %s: %s id %.0f, row at %s (copy of row %d), slot at %s', user.name, user.table, user.id,
                                  hex(user.row), user.source, hex(user.slot)))
            end
        end
    end
    if #spare.order > 0 or config.canary then
        add('')
        add('[borrowed rows] explosion rows that may be borrowed: ' .. table.concat(SPARE.ExplosionSettings or {}, ' '))
        for _, user in ipairs(spare.order) do
            add(string.format('  %s: %s row %d (as a copy of row %d)', user.name, user.table, user.id, user.source))
        end
        if config.canary then
            add('canary: ' .. own_bullet_state('canary'):upper() .. ' - every row of the list is a copy of explosion row '
                .. tostring(MARKER.ExplosionSettings) .. ' (smoke); anything that uses one shows smoke instead')
        end
    end
    add('')
    add('[tables] needed by the config: name copies | address size origin')
    local needed, names = needed_tables(), {}
    for name in pairs(needed) do names[#names + 1] = name end
    table.sort(names)
    for _, name in ipairs(names) do
        local spec = SPECS[name]
        add(name .. ' copies=' .. #spec.blocks)
        for _, block in ipairs(spec.blocks) do
            add(string.format('  %s size=%d origin=%s%s', hex(block.address), block.size, tostring(block.origin),
                              block.problem and (' PROBLEM: ' .. block.problem) or ''))
        end
    end
    if #names == 0 then add('none') end
    add(string.format('search: passes=%d allocations=%d last_pass_seconds=%.2f slowest_query_ms=%.2f at %s',
                      search.passes, search.allocations, search.seconds, search.slowest_query * 1000,
                      hex(search.slowest_at)))
    add('')
    add('[config lines]')
    for _, request in ipairs(config.requests) do
        local head = string.format('line %d [%s: %s] %s', request.line, request.category, request.item, request.text)
        if request.status ~= 'accepted' then
            add(head .. ' -> ' .. tostring(request.status):upper() .. ': ' .. tostring(request.reason))
        elseif request.own_item then
