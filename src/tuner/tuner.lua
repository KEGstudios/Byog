local function parse_bool(text)
    text = text:lower()
    if text == 'true' or text == 'yes' or text == 'on' or text == '1' then return true end
    if text == 'false' or text == 'no' or text == 'off' or text == '0' then return false end
    return nil
end

-- 'N', 'N%', '+N', '-N' applied to the game's value -> number, or nil + reason
local function evaluate(expression, stock)
    local text = expression:gsub('%s+', ''):gsub(',', '.')
    local percent = text:match('^([%d%.]+)%%$')
    if percent then
        local n = tonumber(percent)
        if not n then return nil, 'not a number' end
        return stock * n / 100
    end
    local sign, amount = text:match('^([%+%-])([%d%.]+)$')
    if sign then
        local n = tonumber(amount)
        if not n then return nil, 'not a number' end
        if sign == '+' then return stock + n end
        return stock - n
    end
    local n = text:match('^[%d%.]+$') and tonumber(text)
    if not n then return nil, 'not a number (use 120, 150%, +15 or -5)' end
    return n
end

-- Turns one request (category, item, stat, expression) into field targets, or rejects it.
local function resolve_request(request)
    local item = ITEM_BY_NAME[request.category .. ':' .. request.item:lower()]
    if not item then
        request.status, request.reason = 'rejected', 'unknown ' .. request.category .. ' (see catalog.txt)'
        return
    end
    local stats, nonzero = { request.stat }, false
    local alias = ALIASES[request.stat]
    if alias then stats, nonzero = alias.targets, alias.mode == 'nonzero' end
    request.targets = {}
    for _, stat in ipairs(stats) do
        local entry, range = item.stats[stat], RANGES[stat]
        if entry and range and not (nonzero and entry.field.stock == 0) then
            if entry.attachment then
                request.status = 'rejected'
                request.reason = stat .. " is set by this weapon's default attachment; not editable in this version"
                return
            end
            local value, why = evaluate(request.expression, entry.field.stock)
            if not value then request.status, request.reason = 'rejected', why return end
            if range.integer or entry.field.storage ~= 'f32' then value = math.floor(value + 0.5) end
            if value ~= value or value < range.min or value > range.max then
                request.status = 'rejected'
                request.reason = string.format('%s = %s is outside the allowed range %s .. %s', stat,
                    show(value, 'f32'), show(range.min, 'f32'), show(range.max, 'f32'))
                return
            end
            if encode(value, entry.field.storage) == nil then
                request.status, request.reason = 'rejected', stat .. ' = ' .. tostring(value) .. ' cannot be stored'
                return
            end
            request.targets[#request.targets + 1] = { stat = stat, field = entry.field, value = value }
        elseif not alias then
            request.status = 'rejected'
            request.reason = 'this ' .. request.category .. ' has no stat "' .. stat .. '" (see catalog.txt)'
            return
        end
    end
    if #request.targets == 0 then
        request.status, request.reason = 'rejected', 'nothing to set: no "' .. request.stat .. '" value on this item'
        return
    end
    request.status = 'accepted'
end

-- Parses the config text and the API overrides into `desired`.
local function build_desired(text)
    config.requests, config.problems = {}, {}
    config.enabled, config.reload_key, config.reload_vk = true, 'F10', 0x79
    config.auto_reload, config.rescan = 0, DEFAULT_RESCAN_SECONDS
    local section, line_number = nil, 0
    local by_stat = {}   -- 'category:item:stat' -> request (a later line replaces an earlier one)
    for raw in ((text or '') .. '\n'):gmatch('([^\n]*)\n') do
        line_number = line_number + 1
        local line = trim((raw:gsub('#.*$', ''):gsub('\r', '')))
        if line ~= '' then
            local header = line:match('^%[(.-)%]$')
            local key, value = line:match('^([^=]+)=(.*)$')
            if header then
                local category, item = header:match('^%s*([%w_]+)%s*:%s*(.-)%s*$')
                if trim(header):lower() == 'settings' then
                    section = { settings = true }
                elseif category and item ~= '' then
                    section = { category = category:lower(), item = item }
                else
                    section = nil
                    config.problems[#config.problems + 1] = 'line ' .. line_number .. ': cannot read section "' .. line .. '"'
                end
            elseif key and section then
                key, value = trim(key):lower(), trim(value)
                if section.settings then
                    if key == 'enabled' and parse_bool(value) ~= nil then
                        config.enabled = parse_bool(value)
                    elseif key == 'reload_key' and value:upper():match('^F%d%d?$')
                        and tonumber(value:sub(2)) >= 1 and tonumber(value:sub(2)) <= 12 then
                        config.reload_key = value:upper()
                        config.reload_vk = 0x6F + tonumber(value:sub(2))
                    elseif key == 'auto_reload_seconds' and tonumber(value) and tonumber(value) >= 0 then
                        config.auto_reload = tonumber(value)
                    elseif key == 'rescan_seconds' and tonumber(value) and tonumber(value) >= 0 then
                        config.rescan = tonumber(value)
                    else
                        config.problems[#config.problems + 1] = 'line ' .. line_number .. ': unknown setting "' .. line .. '"'
                    end
                else
                    local request = { line = line_number, category = section.category, item = section.item,
                                      stat = key, expression = value, text = line }
                    by_stat[section.category .. ':' .. section.item:lower() .. ':' .. key] = request
                    config.requests[#config.requests + 1] = request
                end
            else
                config.problems[#config.problems + 1] = 'line ' .. line_number .. ': cannot read "' .. line .. '"'
            end
        end
    end
    for key, expression in pairs(overrides) do
        local category, item, stat = key:match('^([^:]+):([^:]+):(.+)$')
        local previous = by_stat[key]
        if previous then previous.status, previous.reason = 'replaced', 'replaced through the API' end
        local request = { line = 0, category = category, item = item, stat = stat, expression = expression,
                          text = stat .. ' = ' .. expression .. ' (API)' }
        by_stat[key] = request
        config.requests[#config.requests + 1] = request
    end
    -- a later line for the same item and stat replaces the earlier one
    for _, request in ipairs(config.requests) do
        local key = request.category .. ':' .. request.item:lower() .. ':' .. request.stat
        if not request.status and by_stat[key] ~= request then
            request.status, request.reason = 'replaced', 'a later line sets the same stat'
        end
    end
    desired = {}
    if not config.enabled then
        for _, request in ipairs(config.requests) do
            if not request.status then request.status, request.reason = 'off', 'enabled = false' end
        end
        return
    end
    for _, request in ipairs(config.requests) do
        if not request.status then resolve_request(request) end
    end
    -- shared values: different targets for the same field reject every request involved
    local claims = {}
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' then
            for _, target in ipairs(request.targets) do
                local claim = claims[target.field.key]
                if not claim then
                    claims[target.field.key] = { value = target.value, requests = { request }, field = target.field }
                else
                    claim.requests[#claim.requests + 1] = request
                    if not same_value(target.field.storage, claim.value, target.value) then claim.conflict = true end
                end
            end
        end
    end
    for _, claim in pairs(claims) do
        if claim.conflict then
            local lines = {}
            for _, request in ipairs(claim.requests) do lines[#lines + 1] = request.line end
            table.sort(lines)
            for _, request in ipairs(claim.requests) do
                request.status = 'rejected'
                request.reason = 'lines ' .. table.concat(lines, ', ')
                    .. ' ask for different values of the same shared value (' .. claim.field.table .. ' '
                    .. claim.field.record .. ' +' .. claim.field.offset .. ')'
            end
        end
    end
    for _, request in ipairs(config.requests) do
        if request.status == 'accepted' then
            for _, target in ipairs(request.targets) do
                local entry = desired[target.field.key]
                if not entry then
                    entry = { field = target.field, value = target.value, sources = {} }
                    desired[target.field.key] = entry
                end
                entry.sources[#entry.sources + 1] = request
            end
        end
    end
end

local function load_config()
    local text = read_file(MOD.config)
