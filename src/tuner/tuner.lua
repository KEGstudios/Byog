            local new = t.fresh and 'NEW ID ' or ''
            add(string.format('%s -> OWN BULLET %s: projectile row %d -> %s%.0f, damage row %d -> %s%.0f (%d of %d fields in place)%s',
                head, s:upper(), t.src_projectile, new, t.new_projectile, t.src_damage, new, t.new_damage,
                in_place, total, note and ('  ' .. note) or ''))
        elseif request.blast then
            local a = request.blast
            local s, in_place, total, note = own_bullet_state(a.group)
            if s == 'waiting' then note = note or own.index_note end
            add(string.format('%s -> OWN EXPLOSION %s: %s%s (%d of %d fields in place)%s', head, s:upper(),
                a.new_explosion and string.format('explosion row %d -> borrowed row %d', a.blast.explosion, a.new_explosion)
                    or string.format('explosion row %d is its own', a.blast.explosion),
                a.new_damage and string.format(', damage row %d -> NEW ID %.0f', a.blast.damage, a.new_damage) or '',
                in_place, total, (note or a.problem) and ('  ' .. tostring(note or a.problem)) or ''))
        else
            add(head .. (request.warning and ('   WARNING: ' .. request.warning) or '')
                .. (request.yielded and ('   (set by their own lines instead: ' .. request.yielded .. ')') or ''))
            for _, target in ipairs(request.targets) do
                local entry, field = applied[target.field.key], target.field
                local copies, originals, foreign = 0, {}, false
                if entry then
                    for _, copy in pairs(entry.copies) do
                        copies = copies + 1
                        originals[show(copy.original, field.storage)] = true
                        foreign = foreign or copy.foreign
                    end
                end
                local was = {}
                for text in pairs(originals) do was[#was + 1] = text end
                table.sort(was)
                local others = {}
                for _, user in ipairs(field.users) do
                    if user ~= request.item:lower() .. '.' .. target.stat and #others < 12 then others[#others + 1] = user end
                end
                add(string.format('  %s: %s -> %s  %s  copies=%d%s%s%s%s%s', target.stat,
                    target.was_text or (#was > 0 and table.concat(was, '/') or show(field.stock, field.storage)),
                    target.text .. (target.own and ' (own row)' or ''),
                    (entry and entry.state or 'waiting'):upper(), copies,
                    entry and entry.note and ('  (' .. entry.note .. ')') or '',
                    foreign and '  (the value was not the game\'s stock value before we changed it)' or '',
                    target.attachment and '  (value of the default attachment)' or '',
                    target.magazine and ('  (in the weapon\'s own record; the magazine attachment\'s values are '
                        .. (own_bullet_state('magazine:' .. target.magazine.magazine.resource) == 'active'
                            and 'switched off)' or 'NOT switched off yet)')) or '',
                    #others > 0 and ('  also affects: ' .. table.concat(others, ', ')
                                     .. (#field.users - 1 > #others and ', ...' or '')) or ''))
            end
        end
    end
    if #config.requests == 0 then add('none') end
    local leftovers = {}
    for key, entry in pairs(applied) do
        if not desired[key] then leftovers[#leftovers + 1] = key .. ': ' .. tostring(entry.state) .. ' (' .. tostring(entry.note) .. ')' end
    end
    if #leftovers > 0 then
        add('')
        add('[not restored]')
        table.sort(leftovers)
        for _, line in ipairs(leftovers) do add(line) end
    end
    add('')
    add(string.format('[cost] worst_frame_ms=%.2f (during: %s) busy_frames=%d busy_seconds=%.2f',
                      state.worst_frame * 1000, tostring(state.worst_step), state.busy_frames, state.busy_seconds))
    return table.concat(L, '\r\n') .. '\r\n'
end

local last_status = nil
