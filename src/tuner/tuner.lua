-- Writes one value into one copy: checks, write, read back. -> true, or false + reason
local function write_checked(address, field, value)
    local bits = encode(value, field.storage)
    if bits == nil then return false, 'value cannot be stored' end
    local present, protection, shared = A.page(address)
    if not present or shared then return false, 'memory page is not present or not private' end
    local unlocked = false
    if protection == PAGE_READONLY then
        -- In game the component tables (fire rate, handling, magazines...) are in read-only pages.
        if address % 4096 > 4092 or not A.protect(address, PAGE_READWRITE) then
            return false, 'the read-only page could not be made writable'
        end
        unlocked = true
        state.unlocks = state.unlocks + 1
    elseif protection ~= PAGE_READWRITE then
        return false, 'memory page is not writable (protection ' .. tostring(protection) .. ')'
    end
    local wrote = A.write_u32(address, bits)
    if unlocked then
        -- back to read-only whatever happened, and make sure it really is
        local restored = A.protect(address, PAGE_READONLY)
        local _, now = A.page(address)
        if not restored or now ~= PAGE_READONLY then
            state.left_open = state.left_open + 1
            state.errors = state.errors + 1
            log('page of ' .. hex(address) .. ' could not be put back to read-only')
        end
    end
    if not wrote then return false, 'the write was refused by Windows' end
    state.writes = state.writes + 1
    local back = read_field(address, field.storage)
    if not same_value(field.storage, back, value) then
        return false, 'read-back mismatch: wrote ' .. show(value, field.storage) .. ', read ' .. show(back, field.storage)
    end
    return true
end

-- Brings one field to `value` in every copy of its table (value nil: back to the original).
local function sync_field(entry, value)
    local field, spec = entry.field, SPECS[entry.field.table]
    state.step = 'applying ' .. field.table
    local range = nil
    for _, user in ipairs(field.users) do range = range or RANGES[user:match('%.(.+)$')] end
    local seen, done, waiting = {}, 0, 0
    for _, block in ipairs(spec.blocks) do
        seen[block.address] = true
        if parse_block(block) then
            local address = field_address(block, field)
            if address then
                local copy = entry.copies[block.address]
                local current = read_field(address, field.storage)
                if current == nil then
                    entry.note = 'value unreadable at ' .. hex(address)
                else
                    if not copy then
                        -- first touch of this copy: remember what the game had
                        copy = { address = address, original = current, block = block }
                        if not same_value(field.storage, current, field.stock) then
                            copy.foreign = true   -- not the game's stock value: another mod, or an update
                        end
                        entry.copies[block.address] = copy
                    end
                    local target = value
                    if target == nil then target = copy.original end
                    if same_value(field.storage, current, target) then
                        done = done + 1
                    elseif range and (current < range.min - 0.5 or current > range.max + 0.5)
                        and not same_value(field.storage, current, field.stock) then
                        entry.note = 'current value ' .. show(current, field.storage) .. ' is implausible; not touched'
                    else
                        local ok, why = write_checked(address, field, target)
                        if ok then
                            done = done + 1
                            if copy.written then state.rewrites = state.rewrites + 1 end
                            copy.written = value ~= nil
                            if value == nil then state.restores = state.restores + 1 end
                        else
                            entry.note = why
                            state.errors = state.errors + 1
                            log(field.key .. ' at ' .. hex(address) .. ': ' .. why)
                        end
                    end
                end
            else
                entry.note = 'record not found in the table'
            end
        else
            waiting = waiting + 1
        end
        pause()
    end
    for address in pairs(entry.copies) do
        if not seen[address] then entry.copies[address] = nil end   -- that copy is gone
    end
    entry.done = done
    return done
end

-- Makes memory match `desired`: sets what is asked for, restores what no longer is.
local function sync()
    for key, want in pairs(desired) do
        local entry = applied[key]
        if not entry then
            entry = { field = want.field, copies = {} }
            applied[key] = entry
        end
        entry.value, entry.sources, entry.note = want.value, want.sources, nil
        local done = sync_field(entry, want.value)
        entry.state = done > 0 and not entry.note and 'applied' or (entry.note and 'failed' or 'waiting')
    end
    for key, entry in pairs(applied) do
        if not desired[key] then
            entry.note = nil
            local copies = 0
            for _ in pairs(entry.copies) do copies = copies + 1 end
            sync_field(entry, nil)
            if not entry.note or copies == 0 then applied[key] = nil
            else entry.state = 'restore failed' end
        end
    end
end

-- Cheap check of everything applied: block still there, value still ours. -> 'ok' | 'lost' | 'changed'
local function recheck()
    local result = 'ok'
    for _, entry in pairs(applied) do
        for _, copy in pairs(entry.copies) do
            if not valid_block(copy.block) then
                return 'lost'
            end
            -- only values we actually wrote can be "changed back"; a refused write is not retried
            if entry.value ~= nil and copy.written then
                local current = read_field(copy.address, entry.field.storage)
                if not same_value(entry.field.storage, current, entry.value) then result = 'changed' end
            end
        end
        pause()
    end
    return result
end

-- ---------------------------------------------------------------- reports
local function count_states()
    local counts = { applied = 0, waiting = 0, failed = 0, rejected = 0, lines = 0 }
    for _, request in ipairs(config.requests) do
        if request.status ~= 'replaced' then counts.lines = counts.lines + 1 end
        if request.status == 'rejected' then counts.rejected = counts.rejected + 1 end
    end
    for key in pairs(desired) do
        local entry = applied[key]
        local s = entry and entry.state or 'waiting'
        if s == 'applied' then counts.applied = counts.applied + 1
        elseif s == 'waiting' then counts.waiting = counts.waiting + 1
        else counts.failed = counts.failed + 1 end
    end
    return counts
end

local function build_status()
    local L = {}
    local function add(text) L[#L + 1] = text end
    local counts = count_states()
    local verdict
    if state.phase == 'gave_up' then
        verdict = 'FAILED - ' .. tostring(state.failure)
    elseif build.state == 'unchecked' then
        verdict = 'WAITING - checking the game build (nothing written yet)'
    elseif build.state ~= 'verified' then
        verdict = 'REFUSED - this game build is not one this version was verified on; nothing was written'
    elseif not config.enabled then
        verdict = 'DISABLED - enabled = false in config.txt; all values are the game\'s own'
    elseif counts.applied + counts.waiting + counts.failed + counts.rejected == 0 then
        verdict = 'OK - no changes configured'
    elseif counts.waiting + counts.failed + counts.rejected == 0 then
        verdict = 'OK - ' .. counts.applied .. ' values applied'
    else
        verdict = string.format('PARTIAL - %d values applied, %d waiting for their table, %d failed, %d config lines rejected',
                                counts.applied, counts.waiting, counts.failed, counts.rejected)
    end
    state.verdict = verdict
    add(verdict)
    add(MOD.title .. ' v' .. MOD.version)
    add(string.format('phase=%s frame=%d errors=%d writes=%d restores=%d rewrites=%d reloads=%d', state.phase,
                      state.frame, state.errors, state.writes, state.restores, state.rewrites, state.reloads))
    add(string.format('read-only pages opened for a write=%d, not closed again=%d', state.unlocks, state.left_open))
    local loader = rawget(_G, 'CowboyBingusModLoader')
    add('loader: ' .. (type(loader) == 'table' and ('api=' .. tostring(loader.api) .. ' version=' .. tostring(loader.version))
                       or 'CowboyBingusModLoader global not found'))
    if rawget(_G, 'HD2StatTunerRecon') then add('note: the recon build is also installed; remove it, both write STATUS.txt') end
    add('')
    add('[build] ' .. build.state .. (build.label and (': ' .. build.label) or ''))
    for _, m in ipairs(build.modules) do
        add(string.format('%s: size=%s sha256=%s%s', m.name, tostring(m.file_size), tostring(m.sha256),
                          m.note and ('  note: ' .. m.note) or ''))
    end
    if build.state == 'unknown' then
        add('known builds:')
        for _, known in ipairs(BUILDS) do add('  ' .. known.label .. ' exe=' .. known.exe .. ' dll=' .. known.dll) end
    end
    add('')
    add(string.format('[settings] enabled=%s reload_key=%s auto_reload_seconds=%s rescan_seconds=%s', tostring(config.enabled),
                      config.reload_key, tostring(config.auto_reload), tostring(config.rescan)))
    for _, problem in ipairs(config.problems) do add('config problem: ' .. problem) end
    add('')
    add('[tables] needed by the config: name copies | address size origin')
    local needed, names = needed_tables(), {}
    for name in pairs(needed) do names[#names + 1] = name end
    table.sort(names)
    for _, name in ipairs(names) do
        local spec = SPECS[name]
        add(name .. ' copies=' .. #spec.blocks)
        for _, block in ipairs(spec.blocks) do
            add(string.format('  %s size=%d origin=%s%s', hex(block.address), block.size, tostring(block.origin),
                              block.problem and (' PROBLEM: ' .. block.problem) or ''))
        end
    end
    if #names == 0 then add('none') end
    add(string.format('search: passes=%d allocations=%d last_pass_seconds=%.2f slowest_query_ms=%.2f at %s',
                      search.passes, search.allocations, search.seconds, search.slowest_query * 1000,
                      hex(search.slowest_at)))
    add('')
    add('[config lines]')
    for _, request in ipairs(config.requests) do
        local head = string.format('line %d [%s: %s] %s', request.line, request.category, request.item, request.text)
        if request.status ~= 'accepted' then
            add(head .. ' -> ' .. tostring(request.status):upper() .. ': ' .. tostring(request.reason))
        else
            add(head)
            for _, target in ipairs(request.targets) do
                local entry, field = applied[target.field.key], target.field
                local copies, originals, foreign = 0, {}, false
                if entry then
                    for _, copy in pairs(entry.copies) do
                        copies = copies + 1
                        originals[show(copy.original, field.storage)] = true
                        foreign = foreign or copy.foreign
                    end
                end
                local was = {}
                for text in pairs(originals) do was[#was + 1] = text end
                table.sort(was)
                local others = {}
                for _, user in ipairs(field.users) do
                    if user ~= request.item:lower() .. '.' .. target.stat and #others < 12 then others[#others + 1] = user end
                end
                add(string.format('  %s: %s -> %s  %s  copies=%d%s%s%s', target.stat,
                    #was > 0 and table.concat(was, '/') or show(field.stock, field.storage),
                    show(target.value, field.storage),
                    (entry and entry.state or 'waiting'):upper(), copies,
                    entry and entry.note and ('  (' .. entry.note .. ')') or '',
                    foreign and '  (the value was not the game\'s stock value before we changed it)' or '',
                    #others > 0 and ('  also affects: ' .. table.concat(others, ', ')
                                     .. (#field.users - 1 > #others and ', ...' or '')) or ''))
            end
        end
    end
    if #config.requests == 0 then add('none') end
    local leftovers = {}
    for key, entry in pairs(applied) do
        if not desired[key] then leftovers[#leftovers + 1] = key .. ': ' .. tostring(entry.state) .. ' (' .. tostring(entry.note) .. ')' end
    end
    if #leftovers > 0 then
        add('')
        add('[not restored]')
        table.sort(leftovers)
        for _, line in ipairs(leftovers) do add(line) end
    end
    add('')
    add(string.format('[cost] worst_frame_ms=%.2f (during: %s) busy_frames=%d busy_seconds=%.2f',
                      state.worst_frame * 1000, tostring(state.worst_step), state.busy_frames, state.busy_seconds))
    return table.concat(L, '\r\n') .. '\r\n'
end

local last_status = nil
local function write_status(force)
    local ok, text = pcall(build_status)
    if not ok then
        log('status: ' .. tostring(text))
        text = 'FAILED - could not build the status report: ' .. tostring(text) .. '\r\n'
            .. MOD.title .. ' v' .. MOD.version .. '\r\n'
    end
    -- the cost line changes all the time: only rewrite the file when something else did
    local stable = text:gsub('%[cost%][^\r\n]*', ''):gsub('frame=%d+', '')
    if force or stable ~= last_status then
        last_status = stable
        write_file(MOD.status, text)
    end
    if log_dirty then flush_log() end
end

-- Written a few items at a time, so that no frame pays for the whole file.
local function write_catalog()
    local dir = ensure_out_dir()
    local handle = dir and io.open(dir .. '\\' .. MOD.catalog, 'wb')
    if not handle then return end
    handle:write(table.concat({ MOD.title .. ' v' .. MOD.version .. ' catalog',
        'category | item | stat | game value | allowed range | notes',
        'Use these names in config.txt:  [category: item]  then  stat = value', '', '' }, '\r\n'))
    for index = 0, #ITEMS do
        local item = ITEMS[index]
        if item then
            local L = { '[' .. item.category .. ': ' .. item.name .. ']' }
            for _, stat in ipairs(item.stat_order) do
                local entry, range = item.stats[stat], RANGES[stat]
                local notes = {}
                if entry.attachment then notes[#notes + 1] = 'set by the default attachment: not editable yet' end
                if #entry.field.users > 1 then notes[#notes + 1] = 'shared with ' .. (#entry.field.users - 1) .. ' other' end
                L[#L + 1] = string.format('  %s = %s   (%s .. %s%s)%s', stat, show(entry.field.stock, entry.field.storage),
                    show(range.min, 'f32'), show(range.max, 'f32'), range.integer and ', whole numbers' or '',
                    #notes > 0 and ('   # ' .. table.concat(notes, '; ')) or '')
            end
            L[#L + 1] = ''
            handle:write(table.concat(L, '\r\n') .. '\r\n')
        end
        if index % 2 == 0 then pause() end
    end
    handle:write('Shortcuts: ap, blast_ap (every angle that is not 0), recoil, recoil_h, recoil_v, spread, magazine, '
        .. 'spare_magazines, carried\r\n')
    handle:close()
end

-- ---------------------------------------------------------------- the worker
local wake = { at = 0, reload = false, config_check_at = 0 }

local function sleep(seconds)
    wake.at = A.now() + seconds
    coroutine.yield()
end

local function worker_main()
    state.step = 'reading the built-in data'
    parse_data()
    state.phase, state.step = 'checking the build', 'hashing the game files'
    write_status(true)
    check_build()
    state.step = 'reading config.txt'
    load_config()
    state.step = 'writing catalog.txt'
    write_catalog()
    local backoff, next_rescan = 1, 0
    while true do
        if wake.reload then
            wake.reload = false
            state.step = 'reading config.txt'
            load_config()
            backoff = 1
        end
        if build.state ~= 'verified' then
            state.phase = 'refused'
            write_status()
            sleep(3600)
        else
            local missing = missing_tables()
            local have_work = next(desired) ~= nil or next(applied) ~= nil
            local rescan_due = have_work and config.rescan > 0 and A.now() >= next_rescan
            if have_work and (#missing > 0 or state.lost or rescan_due) then
                state.phase, state.step = 'searching', 'searching for tables'
                find_tables()
                state.lost = false
                next_rescan = A.now() + (config.rescan > 0 and config.rescan or 0)
            end
            if have_work then
                state.phase, state.step = 'applying', 'applying values'
                sync()
                state.step = 'writing STATUS.txt'
            end
            if state.report_pending then
                local ok_report, why_report = pcall(log_results)
                if not ok_report then log('report: ' .. tostring(why_report)) end
            end
            missing = missing_tables()
            if not have_work then
                state.phase = 'idle'
                write_status()
                sleep(3600)
            elseif #missing > 0 then
                state.phase = 'waiting for tables'
                write_status()
                sleep(SEARCH_BACKOFF[math.min(backoff, #SEARCH_BACKOFF)])
                backoff = backoff + 1
            else
                backoff = 1
                state.phase = 'applied'
                write_status()
                -- asleep: only cheap read-backs until something needs attention
                while not wake.reload do
                    sleep(RECHECK_SECONDS)
                    if wake.reload then break end
                    state.step = 'rechecking applied values'
                    local result = recheck()
                    if result == 'lost' then
                        state.lost = true
                        log('a patched table is gone (map load?): searching again')
                        break
                    elseif result == 'changed' then
                        log('a patched value was changed back: applying again')
                        break
                    elseif config.rescan > 0 and A.now() >= next_rescan then
                        break
                    end
                end
            end
        end
    end
end

-- ---------------------------------------------------------------- per frame
local worker, key_was_down, last_key_reload = nil, false, -1000

local function request_reload()
    wake.reload, wake.at = true, 0
end

local function tick()
    state.frame = state.frame + 1
    if state.frame < START_FRAME then return end
    -- the reload key: one key-state read per frame; the window is only checked on a press
    local down = A.key_down(config.reload_vk)
    if down and not key_was_down and A.game_in_front() then
        local pressed_at = A.now()
        if pressed_at - last_key_reload >= RELOAD_DEBOUNCE then
            last_key_reload = pressed_at
            log('reload key pressed')
            request_reload()
        end
    end
    key_was_down = down
    if state.frame % STEP_EVERY ~= 0 then return end
    local now = A.now()
    if config.auto_reload > 0 and now >= wake.config_check_at and build.state == 'verified' then
        wake.config_check_at = now + config.auto_reload
        local text = read_file(MOD.config)
        if text ~= nil and text ~= config.text then
            log('config.txt changed on disk')
            request_reload()
        end
    end
    if now < wake.at then return end
    if not worker then worker = coroutine.create(worker_main) end
    deadline = now + FRAME_BUDGET
    local ok, why = coroutine.resume(worker)
    local cost = A.now() - now
    state.busy_frames, state.busy_seconds = state.busy_frames + 1, state.busy_seconds + cost
    if cost > state.worst_frame then state.worst_frame, state.worst_step = cost, tostring(state.step) end
    if not ok then
        state.errors = state.errors + 1
        log('worker failed: ' .. tostring(why))
        worker = nil
        if state.errors >= 5 then
            state.phase, state.failure = 'gave_up', 'too many errors, last: ' .. tostring(why)
            state.retired = true
            write_status(true)
        else
            wake.at = A.now() + 5
            write_status(true)
        end
    end
end

-- ---------------------------------------------------------------- API (for a future UI)
-- Read access to everything the engine knows, and a way to change values without the file.
state.api = {
    version = 1,
    categories = function()
        local seen, list = {}, {}
        for index = 0, #ITEMS do
            local item = ITEMS[index]
            if item and not seen[item.category] then seen[item.category] = true; list[#list + 1] = item.category end
        end
        return list
    end,
    items = function(category)
        local list = {}
        for index = 0, #ITEMS do
            local item = ITEMS[index]
            if item and item.category == category then list[#list + 1] = item.name end
        end
        return list
    end,
    -- -> list of { id, game, current, min, max, integer, editable, shared_with }
    stats = function(category, name)
        local item = ITEM_BY_NAME[tostring(category) .. ':' .. tostring(name):lower()]
        if not item then return nil end
        local list = {}
        for _, stat in ipairs(item.stat_order) do
            local entry, range = item.stats[stat], RANGES[stat]
            local want = desired[entry.field.key]
            list[#list + 1] = { id = stat, game = entry.field.stock, current = want and want.value or entry.field.stock,
                                min = range.min, max = range.max, integer = range.integer,
                                editable = not entry.attachment, shared_with = #entry.field.users - 1 }
        end
        return list
    end,
    -- expression: '120', '150%', '+15', or nil to drop the override
    set = function(category, name, stat, expression)
        overrides[tostring(category):lower() .. ':' .. tostring(name):lower() .. ':' .. tostring(stat):lower()] =
            expression ~= nil and tostring(expression) or nil
        request_reload()
    end,
    reload = request_reload,
    verdict = function() return state.verdict end,
}

-- ---------------------------------------------------------------- startup
log(MOD.title .. ' v' .. MOD.version)
local api_ok, api_failure = pcall(function()
    assert(ffi_ok and ffi, 'LuaJIT FFI is unavailable')
    assert(ffi.abi('64bit'), 'Windows x64 is required')
    A = build_api()
end)
if not api_ok then A = nil end
local ok, failure = pcall(function()
    local loader = rawget(_G, 'CowboyBingusModLoader')
    if type(loader) == 'table' and tonumber(loader.api) and tonumber(loader.api) < 1 then
        error('Bingus Shared Loader is too old (API ' .. tostring(loader.api) .. '); v15 or newer is required', 0)
    end
    if not api_ok then error(tostring(api_failure), 0) end
    -- decoder and encoder must agree on known bit patterns before anything may be written
    for _, case in ipairs({ { 0x3F800000, 1.0 }, { 0x43AF0000, 350.0 }, { 0x42C80000, 100.0 },
                            { 0x3E800000, 0.25 }, { 0xBF000000, -0.5 }, { 0x44610000, 900.0 } }) do
        if bits_to_f32(case[1]) ~= case[2] or A.f32_bits(case[2]) ~= case[1] then
            error('float self-test failed', 0)
        end
    end
    if type(rawget(_G, 'update')) ~= 'function' then error('the game update hook is unavailable', 0) end
end)

if not ok then
    state.phase, state.failure = 'gave_up', tostring(failure)
    log('startup failed: ' .. tostring(failure))
    print('[' .. MOD.global .. '] ' .. tostring(failure))
    write_file(MOD.status, 'FAILED - ' .. tostring(failure) .. '\r\n' .. MOD.title .. ' v' .. MOD.version .. '\r\n')
    flush_log()
    return
end

log('armed; folder ' .. tostring(ensure_out_dir()))
write_file(MOD.status, 'WAITING - starting (nothing written yet)\r\n' .. MOD.title .. ' v' .. MOD.version .. '\r\n')
flush_log()

-- Guarded hook: we never cut other addons out of the update chain.
local original_update = update
local my_update
my_update = function(...)
    if not state.retired then
        local tick_ok, why = pcall(tick)
        if not tick_ok then
            state.errors = state.errors + 1
            log('tick: ' .. tostring(why))
            if state.errors >= 20 then state.retired = true end
        end
    end
    return original_update(...)
end
update = my_update
