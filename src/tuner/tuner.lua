-- little-endian u32 at byte offset `offset` of a hex string
local function hex_word(text, offset)
    local a, b, c, d = text:sub(offset * 2 + 1, offset * 2 + 2), text:sub(offset * 2 + 3, offset * 2 + 4),
        text:sub(offset * 2 + 5, offset * 2 + 6), text:sub(offset * 2 + 7, offset * 2 + 8)
    return tonumber(a, 16) + tonumber(b, 16) * 256 + tonumber(c, 16) * 65536 + tonumber(d, 16) * 16777216
end

local function field_key(table_name, key, offset) return table_name .. '|' .. key .. '|' .. offset end

local function parse_data()
    local count = 0
    for line in DATA:gmatch('[^\n]+') do
        local kind = line:sub(1, 1)
        local f = {}
        for part in (line .. '|'):gmatch('([^|]*)|') do f[#f + 1] = part end
        if kind == 'V' then
            BUILDS[#BUILDS + 1] = { label = f[2], exe = f[3], dll = f[4] }
        elseif kind == 'T' then
            local spec = { name = f[2], type = tonumber(f[3], 16), shape = f[4],
                           stride = tonumber(f[5]), id_at = tonumber(f[6]), blocks = {} }
            SPECS[spec.name], SPEC_BY_TYPE[spec.type] = spec, spec
            SPEC_ORDER[#SPEC_ORDER + 1] = spec.name
        elseif kind == 'I' then
            local item = { index = tonumber(f[2]), category = f[3], name = f[4], entity = f[5],
                           display = f[6] ~= '' and f[6] or nil, stats = {}, stat_order = {} }
            ITEMS[item.index] = item
            ITEM_BY_NAME[item.category .. ':' .. item.name:lower()] = item
        elseif kind == 'F' then
            local item = ITEMS[tonumber(f[2])]
            local key = field_key(f[4], f[5], tonumber(f[6]))
            local field = FIELDS[key]
            if not field then
                field = { key = key, table = f[4], record = f[5], offset = tonumber(f[6]), storage = f[7],
                          stock = tonumber(f[8]), users = {} }
                FIELDS[key] = field
                field_count = field_count + 1
            end
            field.users[#field.users + 1] = item.name .. '.' .. f[3]
            if not item.stats[f[3]] then item.stat_order[#item.stat_order + 1] = f[3] end
            item.stats[f[3]] = { field = field, attachment = f[9] == 'A' }
        elseif kind == 'R' then
            RANGES[f[2]] = { min = tonumber(f[3]), max = tonumber(f[4]), integer = f[5] == '1' }
        elseif kind == 'A' then
            local targets = {}
            for name in f[4]:gmatch('[^,]+') do targets[#targets + 1] = name end
            ALIASES[f[2]] = { mode = f[3], targets = targets }
        elseif kind == 'O' then
            ITEMS[tonumber(f[2])].takeover = { base_projectile = tonumber(f[3]), src_projectile = tonumber(f[4]),
                new_projectile = tonumber(f[5]), src_damage = tonumber(f[6]), new_damage = tonumber(f[7]) }
        elseif kind == 'U' then
            local item = ITEMS[tonumber(f[2])]
            item.switches = item.switches or {}
            item.switches[#item.switches + 1] = { table = f[3], offset = tonumber(f[4]), projectile = tonumber(f[5]) }
        elseif kind == 'W' then
            ROWS[f[2] .. '|' .. f[3]] = f[4]
        elseif kind == 'X' then
            ITEMS[tonumber(f[2])].ammo_delta = { offset = tonumber(f[3]), expected = tonumber(f[4]) }
        elseif kind == 'N' then
            INDEXES[f[2] .. '|' .. f[3]] = { rva = tonumber(f[4], 16), slots = tonumber(f[5]) }
        elseif kind == 'G' then
            local item = ITEMS[tonumber(f[2])]
            item.magazine = { run_at = tonumber(f[3]), run_count = tonumber(f[4]), resource = f[5], base = {} }
            MAGAZINES[f[5]] = MAGAZINES[f[5]] or {}
            MAGAZINES[f[5]][#MAGAZINES[f[5]] + 1] = item
        elseif kind == 'H' then
            ITEMS[tonumber(f[2])].magazine.base[f[3]] = { table = f[4], record = f[5], offset = tonumber(f[6]),
                                                          storage = f[7], stock = tonumber(f[8]) }
        elseif kind == 'Q' then
            CENSUS_TABLE[f[2]] = f[3]
        elseif kind == 'B' then
            local item = ITEMS[tonumber(f[2])]
            local blast = { kind = f[3], explosion = tonumber(f[4]), damage = tonumber(f[5]), own = f[6] == '1',
                            shared_damage = f[7] == '1', switches = {} }
            for switch in f[8]:gmatch('[^,]+') do
                local table_name, offset = switch:match('^(.-):(%d+)$')
                if table_name then
                    blast.switches[#blast.switches + 1] = { table = table_name, offset = tonumber(offset) }
                else
                    blast.switches[#blast.switches + 1] = { offset = tonumber(switch) }
                end
            end
            item.blasts = item.blasts or {}
            item.blasts[#item.blasts + 1] = blast
        elseif kind == 'S' then
            SPARE[f[2]] = {}
            for id in f[3]:gmatch('%d+') do SPARE[f[2]][#SPARE[f[2]] + 1] = tonumber(id) end
        elseif kind == 'P' then
            LIVE_WORDS[f[2]] = {}
            for offset in f[3]:gmatch('%d+') do LIVE_WORDS[f[2]][tonumber(offset)] = true end
        elseif kind == 'Y' then
            MARKER[f[2]] = tonumber(f[3])
        elseif kind == 'C' then
            local entry = { target = f[2], name = f[3], type = tonumber(f[4], 16), shape = f[5],
                            stride = tonumber(f[6]), id_at = 0, offline = tonumber(f[7]), paths = {} }
            for path in f[8]:gmatch('[^;]+') do
                local steps = {}
                for step in path:gmatch('[^,]+') do
                    if step:sub(1, 1) == 'a' then steps[#steps + 1] = { array = tonumber(step:sub(2)) }
                    else steps[#steps + 1] = { add = tonumber(step) } end
                end
                entry.paths[#entry.paths + 1] = steps
            end
            CENSUS[#CENSUS + 1] = entry
        end
        count = count + 1
        if count % 50 == 0 then pause() end
    end
    log('data: ' .. #BUILDS .. ' builds, ' .. #SPEC_ORDER .. ' tables, ' .. (#ITEMS + 1) .. ' items, '
        .. field_count .. ' fields')
end

-- ---------------------------------------------------------------- build gate
local build = { state = 'unchecked', modules = {} }

local function hash_module(name)
    local info = { name = name or 'helldivers2.exe' }
    local base, path = A.module(name)
    if not base or not path then info.note = 'not loaded'; return info end
    info.path = path
    local handle, size = A.open(path)
    if not handle then info.note = 'file could not be opened'; return info end
    info.file_size = size
    local context = A.sha256_begin()
    if not context then
        info.note = 'SHA-256 unavailable'
    else
        local total, ok = 0, true
        while true do
            local n = A.read_file(handle)
            if n == nil then ok = false break end
            if n == 0 then break end
            if not A.sha256_update(context, n) then ok = false break end
            total = total + n
            pause()
        end
        local digest = A.sha256_finish(context)
        if ok and digest and total == size then info.sha256 = digest
        else info.note = 'hashing failed after ' .. total .. ' bytes' end
    end
    A.close(handle)
    return info
end

-- Sets build.state to 'verified' only when BOTH files hash to the same known build.
local function check_build()
    local exe, dll = hash_module(nil), hash_module('game.dll')
    build.modules = { exe, dll }
    build.state, build.label = 'unknown', nil
    for _, known in ipairs(BUILDS) do
        if exe.sha256 and dll.sha256 and exe.sha256 == known.exe and dll.sha256 == known.dll then
            build.state, build.label = 'verified', known.label
        end
    end
    log('build: ' .. build.state .. (build.label and (' (' .. build.label .. ')') or '')
        .. ' exe=' .. tostring(exe.sha256 or exe.note) .. ' dll=' .. tostring(dll.sha256 or dll.note))
end

-- ---------------------------------------------------------------- finding tables
local search = { passes = 0, allocations = 0, seconds = 0, slowest_query = 0, slowest_at = 0 }

local function valid_block(block)
    return A.u32(block.address) == LDLD and A.u32(block.address + 4) == 1
        and A.u32(block.address + 8) == block.type and A.u32(block.address + 12) == block.size
end

-- Follows a chain of back-to-back blocks from `address`; keeps the blocks of wanted tables.
local function walk(address, origin, found)
    local steps = 0
    while steps < 200000 do
        if A.u32(address) ~= LDLD or A.u32(address + 4) ~= 1 then return end
        local kind, size = A.u32(address + 8), A.u32(address + 12)
        if not kind or kind == 0 or not size or size == 0 or size > MAX_BLOCK then return end
        local spec = SPEC_BY_TYPE[kind]
        if spec and not found[address] then
            found[address] = { address = address, type = kind, size = size, spec = spec,
                               origin = steps == 0 and origin or 'chain' }
        end
        steps = steps + 1
        local after, next_address = address + 24 + size, nil
        for skip = 0, 16, 4 do
            if A.u32(after + skip) == LDLD and A.u32(after + skip + 4) == 1 then
                next_address = after + skip
                break
            end
        end
        if not next_address then return end
        address = next_address
        pause()
    end
end

-- One pass over the allocations of the process: is there a table at the start of each?
-- (In-game recon: every table we use sits there or in the chain behind one.)
local function find_tables()
    local started, found = A.now(), {}
    search.allocations = 0
    local cursor = ADDRESS_START
    while cursor < ADDRESS_END do
        local t0 = A.now()
        local base, size, allocated = A.allocation(cursor)
        local cost = A.now() - t0
        if cost > search.slowest_query then search.slowest_query, search.slowest_at = cost, cursor end
        if not base then break end
        if allocated then
            search.allocations = search.allocations + 1
            if A.readable_start(base, size) then
                if A.u32(base) == LDLD and A.u32(base + 4) == 1 then
                    walk(base, 'allocation+0', found)
                elseif A.u32(base + 4) == LDLD and A.u32(base + 8) == 1 then
                    walk(base + 4, 'allocation+4', found)
                end
            end
        end
        local next_cursor = base + size
        if next_cursor <= cursor then next_cursor = cursor + 4096 end
        cursor = next_cursor
        pause()
    end
    -- merge: keep parsed blocks that are still there, add new ones, drop the rest
    for _, name in ipairs(SPEC_ORDER) do
        local spec, kept = SPECS[name], {}
        for _, block in ipairs(spec.blocks) do
            if found[block.address] and found[block.address].size == block.size then
                kept[#kept + 1] = block
                found[block.address] = nil
            end
        end
        spec.blocks = kept
    end
    for _, block in pairs(found) do
        block.spec.blocks[#block.spec.blocks + 1] = block
    end
    for _, name in ipairs(SPEC_ORDER) do
        table.sort(SPECS[name].blocks, function(x, y) return x.address < y.address end)
    end
    search.passes = search.passes + 1
    search.seconds = A.now() - started
    state.passes = search.passes
end

-- Keyed table: buckets (u64 entity, u32 record index, u32 0), twice as many as entities, then
-- fixed-size records. The bucket count is derived from the content, never assumed.
local function parse_keyed(block)
    local payload, size, stride = block.address + 24, block.size, block.spec.stride
    local limit = math.floor(size / (16 + stride / 2)) + 4
    local count, live, top, fits = 0, 0, -1, {}
    local offset, stop = 0, false
    while not stop and offset + 16 <= size and count <= limit do
        local want = math.min(8192, size - offset)
        want = want - want % 16
        if want < 16 or not A.read(payload + offset, want) then break end
        local w = A.words
        for k = 0, want / 16 - 1 do
            local lo, hi, index, pad = w[k * 4], w[k * 4 + 1], w[k * 4 + 2], w[k * 4 + 3]
            if pad ~= 0 or index > 1000000 or count > limit then stop = true break end
            count = count + 1
            if lo ~= 0 or hi ~= 0 then
                live = live + 1
                if index > top then top = index end
            end
            local rest = size - count * 16
            if count == 2 * live and rest > 0 and rest % stride < 8 then
                local records = (rest - rest % stride) / stride
                if records > top and records <= live + 2 then
                    fits[#fits + 1] = { buckets = count, records = records }
                end
            end
        end
        offset = offset + want
        pause()
    end
    if #fits ~= 1 then return nil, #fits .. ' bucket layouts fit (need exactly 1)' end
    local fit, index = fits[1], {}
    offset = 0
    while offset < fit.buckets * 16 do
        local want = math.min(8192, fit.buckets * 16 - offset)
        if not A.read(payload + offset, want) then return nil, 'bucket array unreadable' end
        local w = A.words
        for k = 0, want / 16 - 1 do
            local lo, hi = w[k * 4], w[k * 4 + 1]
            if lo ~= 0 or hi ~= 0 then
                local key = string.format('%08X%08X', hi, lo)
                if index[key] == nil then
                    local record = w[k * 4 + 2]
                    if record >= fit.records then return nil, 'record index out of range' end
                    index[key] = record
                end
            end
        end
        offset = offset + want
        pause()
    end
    block.records_at, block.index, block.count = payload + fit.buckets * 16, index, fit.records
    block.limit = payload + size
    return true
end

-- Row table: DLArray (u64 absolute pointer in memory, u64 count), then rows carrying a u32 id.
local function parse_rows(block)
    local payload, size, stride = block.address + 24, block.size, block.spec.stride
    local pointer, count = A.u64(payload), A.u64(payload + 8)
    if not pointer or not count then return nil, 'array head unreadable' end
    local rows_at
    if pointer < size then rows_at = payload + pointer
    elseif pointer >= payload and pointer < payload + size then rows_at = pointer
    else return nil, 'rows are outside the block' end
    if count == 0 or (rows_at - payload) + count * stride > size then
        return nil, 'rows do not fit (count ' .. count .. ')'
    end
    local index = {}
    local per_read = math.max(1, math.floor(FILE_CHUNK / stride))
    local row = 0
    while row < count do
        local n = math.min(per_read, count - row)
        if not A.read(rows_at + row * stride, n * stride) then return nil, 'rows unreadable' end
        local bytes = A.buffer
        for k = 0, n - 1 do
            local at = k * stride + block.spec.id_at
            local id = bytes[at] + bytes[at + 1] * 256 + bytes[at + 2] * 65536 + bytes[at + 3] * 16777216
            if index[id] == nil then index[id] = row + k end
        end
        row = row + n
        pause()
    end
    block.records_at, block.index, block.count = rows_at, index, count
    block.limit = payload + size
    return true
end

-- Delta storage: five arrays; the fifth (pointer at +64, byte count at +72) is the raw data the
-- attachment deltas copy from.
local function parse_delta_storage(block)
    local payload = block.address + 24
    local pointer, count = A.u64(payload + 64), A.u64(payload + 72)
    if not pointer or not count or count == 0 or count > MAX_BLOCK then return nil, 'data array head unreadable' end
    if pointer < block.size then pointer = payload + pointer end
    block.records_at, block.index, block.count, block.limit = pointer, {}, count, pointer + count
    -- the third array (pointer at +32, count at +40): 12-byte runs, one per component an attachment changes
    local runs, run_count = A.u64(payload + 32), A.u64(payload + 40)
    if runs and run_count and run_count > 0 and run_count * 12 <= MAX_BLOCK then
        if runs < block.size then runs = payload + runs end
        block.components_at, block.components_end = runs, runs + run_count * 12
    end
    return true
end

local function parse_block(block)
    if block.index or block.problem then return block.index ~= nil end
    state.step = 'reading table ' .. block.spec.name
    local ok, why
    if block.spec.shape == 'K' then ok, why = parse_keyed(block)
    elseif block.spec.shape == 'D' then ok, why = parse_delta_storage(block)
    else ok, why = parse_rows(block) end
    if not ok then
        block.problem = why
        log(block.spec.name .. ' at ' .. hex(block.address) .. ' cannot be parsed: ' .. tostring(why))
    end
    return ok == true
end

-- Address of `field` in `block`, or nil when the record is not in this table.
local function field_address(block, field)
    if block.spec.shape == 'D' then
        if field.record == 'components' then
            if not block.components_at or block.components_at + field.offset + 4 > block.components_end then return nil end
            return block.components_at + field.offset
        end
        local address = block.records_at + field.offset
        if address + 4 > block.limit then return nil end
        return address
    end
    local key = field.record
    if block.spec.shape == 'R' then key = tonumber(key) end
    local record = block.index[key]
    if record == nil then return nil end
    local address = block.records_at + record * block.spec.stride + field.offset
    if address < block.address + 24 or address + 4 > block.limit then return nil end
    return address
end

local function read_field(address, storage)
    local bits = A.u32(address)
    if bits == nil then return nil end
    if storage == 'f32' then return bits_to_f32(bits) end
    if storage == 'i32' and bits >= 2147483648 then return bits - 4294967296 end
    return bits
end

-- value -> bit pattern, or nil when it cannot be represented exactly as intended
local function encode(value, storage)
    if storage == 'f32' then
        local bits = A.f32_bits(value)
        if not close_enough(bits_to_f32(bits), value) then return nil end   -- encoder vs decoder
        return bits
    end
    if value ~= math.floor(value) then return nil end
    if storage == 'i32' then
        if value < -2147483648 or value > 2147483647 then return nil end
        if value < 0 then return value + 4294967296 end
        return value
    end
    if value < 0 or value > 4294967295 then return nil end
    return value
end

-- ---------------------------------------------------------------- rows of our own (experimental)
-- In-game probe (v0.3.2): the game finds a projectile or damage row as [index + id * 8], where
-- `index` is a fixed array inside game.dll, and it does not compare the id with the number of rows.
-- An id far above the real ones therefore reads its "slot" from memory above game.dll. We allocate
-- memory of our own there and put rows and pointers to those rows inside: the id that lands on such a
-- pointer is a new row id. Nothing of the game's is changed by this. A weapon is switched to such
-- ids only after each index has been checked against its table: every real id must lead to its row.
-- (In game, v0.4.1: a new projectile id works, solo and as a client in someone else's lobby.)
local OWN_TYPE = 0x4E574F4B      -- tag of our block; not a table type of the game
local OWN_CAPACITY = 256         -- rows of our own per table
local OWN_SIZE, OWN_SLOTS_AT, OWN_ROWS_AT = 0x20000, 0x100, 0x2000
local OWN_DAMAGE_AT = 60         -- the damage row id inside a projectile row
local OWN_TABLES = { 'ProjectileSettings', 'DamageSettings' }
local own = { state = 'unused', tables = {}, order = {} }

local function own_name(table_name) return 'own:' .. table_name end
local function known_index(table_name)
    return build.label and INDEXES[build.label .. '|' .. table_name] or nil
end

-- Allocates our block in reach of the game's indexes. -> true, or nil + reason
local function own_prepare()
    if own.block then return true end
    if own.state == 'failed' then return nil, own.note end
    if build.state ~= 'verified' then return nil, 'the game build is not verified' end
    local function fail(why)
        own.state, own.note = 'failed', why
        log('own rows: ' .. why)
        return nil, why
    end
    local dll = A.module('game.dll')
    if not dll then return fail('game.dll is not loaded') end
    -- where each table's slots and rows will sit inside the block
    local plan, rows_at, highest = {}, OWN_ROWS_AT, 0
    for n, name in ipairs(OWN_TABLES) do
        local known, spec = known_index(name), SPECS[name]
        if not known or not spec then return fail('this build has no known index for ' .. name) end
        local index = dll + known.rva
        if index % 8 ~= 0 or spec.stride % 4 ~= 0 then return fail('the ' .. name .. ' index is not aligned') end
        plan[n] = { name = name, index = index, stride = spec.stride, slots_at = OWN_SLOTS_AT + (n - 1) * OWN_CAPACITY * 8,
                    rows_at = rows_at }
        rows_at = rows_at + OWN_CAPACITY * spec.stride
        if index > highest then highest = index end
    end
    if OWN_SLOTS_AT + #OWN_TABLES * OWN_CAPACITY * 8 > OWN_ROWS_AT or rows_at > OWN_SIZE then
        return fail('the block layout does not fit')
    end
    local cursor, steps, attempts, address = highest, 0, 0, nil
    while cursor < ADDRESS_END and steps < 20000 and attempts < 16 do
        local base, size, allocated = A.allocation(cursor)
        if not base then break end
        local following = base + size
        if not allocated then
            local at = cursor + (-cursor) % 65536
            -- the id of our last slot must stay a positive 32-bit number, for every table
            local in_reach = true
            for _, t in ipairs(plan) do
                if (at + t.slots_at - t.index) / 8 + OWN_CAPACITY >= 2147483648 then in_reach = false end
            end
            if not in_reach then break end
            if at + OWN_SIZE <= following then
                attempts = attempts + 1
                if A.alloc(at, OWN_SIZE) == at then address = at break end
            end
        end
        if following <= cursor then following = cursor + 65536 end
        cursor = following
        steps = steps + 1
        pause()
    end
    if not address then return fail('no free memory in reach of the game\'s indexes') end
    local header = { LDLD, 1, OWN_TYPE, OWN_SIZE - 24 }
    for n, word in ipairs(header) do
        if not A.write_u32(address + (n - 1) * 4, word) or A.u32(address + (n - 1) * 4) ~= word then
            return fail('our own memory at ' .. hex(address) .. ' cannot be written')
        end
    end
    own.block = address
    for _, t in ipairs(plan) do
        local own_spec = { name = own_name(t.name), type = OWN_TYPE, shape = 'R', stride = t.stride, id_at = 0, blocks = {} }
        t.block = { address = address, type = OWN_TYPE, size = OWN_SIZE - 24, spec = own_spec, origin = 'own',
                    records_at = address + t.rows_at, index = {}, count = 0, limit = address + OWN_SIZE }
        own_spec.blocks[1] = t.block
        SPECS[own_spec.name] = own_spec
        t.first_id, t.count, t.users = (address + t.slots_at - t.index) / 8, 0, {}
        own.tables[t.name] = t
        log(string.format('own rows: %s index at %s, first new id %.0f', t.name, hex(t.index), t.first_id))
    end
    own.state = 'ready'
    log('own rows: block at ' .. hex(address))
    return true
end

-- The new row id of `item` in `table_name`: a copy of row `source`. A projectile row also gets
-- `damage` as its damage row id. -> id, or nil + reason
local function own_row(item, table_name, source, damage, purpose)
    local ok, why = own_prepare()
    if not ok then return nil, why end
    local t = own.tables[table_name]
    local key = item.name .. (purpose or '')
    local user = t.users[key]
    if user then return user.id end
    if t.count >= OWN_CAPACITY then return nil, 'no room for another row of our own' end
    local stock = ROWS[table_name .. '|' .. source]
    if not stock or #stock ~= t.stride * 2 then return nil, 'the stock row ' .. table_name .. ' ' .. source .. ' is not known' end
    local k = t.count
    local id, row_at, slot_at = t.first_id + k, t.block.records_at + k * t.stride, own.block + t.slots_at + k * 8
    for offset = 0, t.stride - 4, 4 do
        local word = hex_word(stock, offset)
        if offset == 0 then word = id elseif damage and offset == OWN_DAMAGE_AT then word = damage end
        if not A.write_u32(row_at + offset, word) or A.u32(row_at + offset) ~= word then
            return nil, 'our own row could not be written'
        end
        if offset % 64 == 60 then pause() end
    end
    local high = math.floor(row_at / 4294967296)
    if not A.write_u32(slot_at, row_at - high * 4294967296) or not A.write_u32(slot_at + 4, high)
        or A.u64(slot_at) ~= row_at or t.index + id * 8 ~= slot_at then
        return nil, 'the slot of our own row could not be written'
    end
    t.block.index[id], t.count, t.block.count = k, k + 1, k + 1
    t.users[key] = { id = id, row = row_at, slot = slot_at, source = source, name = key, table = table_name }
    own.order[#own.order + 1] = t.users[key]
    log(string.format('own rows: %s -> new %s id %.0f (row at %s, copy of row %d)', key, table_name, id,
                      hex(row_at), source))
    return id
end

-- Does the game's index lead every real id of `table_name` to its row in a table we found?
-- -> true; false + reason (it does not: never switch a weapon); nil + reason (cannot tell yet)
local function own_index_ok(table_name)
    local known, spec, t = known_index(table_name), SPECS[table_name], own.tables[table_name]
    if not t or not known then return false, 'no block of our own' end
    local bytes = known.slots * 8
    if not A.readable_private(t.index) or not A.readable_private(t.index + bytes - 1) then
        return nil, 'the ' .. table_name .. ' index is not in memory yet'
    end
    local parsed, reason = 0, 'the ' .. table_name .. ' table is not loaded yet'
    for _, block in ipairs(spec.blocks) do
        if parse_block(block) then
            parsed = parsed + 1
            if block.count + 1 ~= known.slots then
                reason = table_name .. ' has ' .. block.count .. ' rows, the index was measured with ' .. (known.slots - 1)
            elseif not A.read(t.index, bytes) then
                reason = 'the ' .. table_name .. ' index cannot be read'
            else
                local good = A.words[0] == 0 and A.words[1] == 0
                for id, row in pairs(block.index) do
                    local address = block.records_at + row * spec.stride
                    local high = math.floor(address / 4294967296)
                    if id < 1 or id >= known.slots or A.words[2 * id + 1] ~= high
                        or A.words[2 * id] ~= address - high * 4294967296 then
                        good = false
                        break
                    end
                end
                if good then return true end
                reason = 'the ' .. table_name .. ' index does not lead to the rows of the table'
            end
        end
        pause()
    end
    if parsed == 0 then return nil, reason end
    return false, reason
end

-- ---------------------------------------------------------------- borrowed rows
-- Explosion ids are compared with the number of rows (probe v0.3.2), so an explosion row of an item's
-- own cannot have a new id: an existing row is borrowed from a short list of rows that no table in
-- memory refers to (census v0.8.0). Such a row is overwritten with a copy of the item's row and put
-- back when it is no longer needed. An id that only code uses is invisible to the census, so the list
-- is a guess; the canary (see build_desired) is the in-game test of it.
local spare = { users = {}, order = {}, next = {} }

-- The borrowed row of `key` in `table_name`. -> row id, or nil + reason
local function spare_row(key, table_name, source)
    local user = spare.users[table_name .. '|' .. key]
    if user then return user.id end
    local pool = SPARE[table_name] or {}
    local n = (spare.next[table_name] or 0) + 1
    if n > #pool then return nil, 'no row is left to borrow in ' .. table_name end
    spare.next[table_name] = n
    user = { id = pool[n], name = key, table = table_name, source = source }
    spare.users[table_name .. '|' .. key], spare.order[#spare.order + 1] = user, user
    log(string.format('borrowed rows: %s -> %s row %d (as a copy of row %d)', key, table_name, user.id, source))
    return user.id
end

