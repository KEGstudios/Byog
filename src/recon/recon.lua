-- ---------------------------------------------------------------- tuning
local START_FRAME = 120          -- let the game start before touching anything
local STEP_EVERY = 2             -- work on every 2nd frame only
local FRAME_BUDGET = 0.0015      -- seconds of work per working frame
local CHUNK = 262144             -- bytes per memory read while sweeping
local REST_SECONDS = 20          -- pause between rounds
local MAX_ROUNDS = 180           -- about an hour, then the addon retires
local MAX_SWEEPS = 3             -- full memory sweeps per session
local SWEEP_GAP_SECONDS = 90
local MAX_BLOCK = 0x10000000     -- 256 MB: larger "payload sizes" are not tables
local MAX_MISMATCH_LINES = 40
local ADDRESS_START, ADDRESS_END = 0x10000, 0x7FFFFFFF0000
local LDLD = 0x444C444C          -- 'LDLD' read as a little-endian u32
local MEM_COMMIT, MEM_PRIVATE = 0x1000, 0x20000
local PAGE_READONLY, PAGE_READWRITE = 0x02, 0x04

local state = {
