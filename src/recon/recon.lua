-- HD2-Addon: mods/keg/stat_tuner_recon
-- HD2 Stat Tuner - RECON build. Read-only: this file never writes to game memory.
-- It finds the game's data tables in this process, compares a watch-list of values with the
-- offline data it was generated from, and reports everything to
--   %LOCALAPPDATA%\HD2StatTuner\STATUS.txt   (what to send back)
--   %LOCALAPPDATA%\HD2StatTuner\recon.log    (developer log)
-- Requires Bingus Shared Loader (API 1). Runs on LuaJIT (Lua 5.1 syntax only).

