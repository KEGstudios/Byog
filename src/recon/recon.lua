    return 'loader: api=' .. tostring(loader.api) .. ' version=' .. tostring(loader.version)
end

local function build_status()
    local L = {}
    local function add(text) L[#L + 1] = text end
    local found, wanted, core_missing = 0, 0, {}
    local w_total, w_matched, w_differing, w_missing = 0, 0, 0, 0
    for _, name in ipairs(SPEC_ORDER) do
        local spec = SPECS[name]
        wanted = wanted + 1
        if #spec.copies > 0 then found = found + 1 else core_missing[#core_missing + 1] = name end
        local first = spec.copies[1]
        if first and first.watch then
            w_total = w_total + first.watch.total
            w_matched = w_matched + first.watch.matched
            w_differing = w_differing + first.watch.differing
            w_missing = w_missing + first.watch.missing
        elseif WATCH[name] then
            w_total = w_total + #WATCH[name]
            w_missing = w_missing + #WATCH[name]
        end
    end
    local verdict
    if state.phase == 'gave_up' then
        verdict = 'FAILED - ' .. tostring(state.failure)
    elseif state.round == 0 or wanted == 0 then
        verdict = 'WAITING - first scan not finished yet (keep the game running)'
    elseif found == wanted and w_total > 0 and w_matched == w_total then
        verdict = 'OK - all ' .. wanted .. ' tables found, all ' .. w_total .. ' watched values match the offline data'
    else
        verdict = string.format('PARTIAL - %d of %d tables found; watched values: %d match, %d differ, %d not reachable',
                                found, wanted, w_matched, w_differing, w_missing)
    end
    state.verdict = verdict
    add(verdict)
    add('read-only build: nothing was written to game memory')
    add(MOD.title .. ' v' .. MOD.version)
    add(string.format('phase=%s round=%d sweeps=%d frame=%d errors=%d', state.phase, state.round, state.sweeps,
                      state.frame, state.errors))
    add(loader_line())
    add('self_read=' .. tostring(state.self_read) .. ' watch_values=' .. watch_total)
    add('')
    add('[build]')
    if not build.done then add('not identified yet (done after the first full sweep)') end
    for _, m in ipairs(build.modules) do
        add(string.format('%s: path=%s', m.name, tostring(m.path)))
        add(string.format('  file_size=%s sha256=%s', tostring(m.file_size), tostring(m.sha256)))
        add(string.format('  pe_timestamp=%s image_size=%s pe_checksum=%s%s',
            m.timestamp and hex(m.timestamp) or '?', tostring(m.image_size),
            m.checksum and hex(m.checksum) or '?', m.note and ('  note: ' .. m.note) or ''))
    end
    add('')
    add('[scan]')
    add(string.format('last pass: mode=%s regions=%d readable=%d blocks=%d seconds=%.1f', tostring(state.mode),
        scan.regions, scan.readable, #census.list, scan.seconds))
    add(string.format('sweep: bytes=%.0f read_failures=%d pages_not_in_memory=%d', scan.bytes,
                      scan.read_failures, scan.skipped_pages))
    add(string.format('cost: worst_frame_ms=%.2f busy_frames=%d busy_seconds=%.1f slowest_region_query_ms=%.2f',
        state.worst_frame * 1000, state.busy_frames, state.busy_seconds, scan.slowest_query * 1000))
    add('')
    add('[tables] name type copies | per copy: address payload origin details')
    for _, name in ipairs(SPEC_ORDER) do
        local spec = SPECS[name]
        add(string.format('%s %08X shape=%s stride=%d copies=%d', name, spec.type, spec.shape, spec.stride,
                          #spec.copies))
        local shown = 0
        for _, r in ipairs(spec.copies) do
            shown = shown + 1
            if shown > 12 then add('  ... ' .. (#spec.copies - 12) .. ' more copies') break end
            local detail
            if r.problem then
                detail = 'PROBLEM: ' .. r.problem .. (r.head and (' head=' .. r.head) or '')
            elseif spec.shape == 'K' then
                detail = string.format('records=%d entities=%d buckets=%d slack=%d', r.count or -1, r.entries or -1,
                                       r.buckets or -1, r.slack or -1)
            elseif spec.shape == 'R' then
                detail = string.format('rows=%d ids=%d duplicates=%d tail=%d array=%s', r.count or -1,
                                       r.entries or -1, r.duplicates or -1, r.tail or -1, tostring(r.form))
            elseif spec.shape == 'D' then
                detail = tostring(r.form) .. '; ' .. tostring(r.arrays)
            else
                detail = ''
            end
            if r.watch then
                detail = detail .. string.format(' | watch %d: match %d, differ %d, key missing %d, unreadable %d',
                    r.watch.total, r.watch.matched, r.watch.differing, r.watch.missing, r.watch.unreadable)
            end
            add(string.format('  %s size=%d origin=%s %s', hex(r.address), r.size, tostring(r.origin), detail))
        end
    end
    add('')
    add('[differences] first copy of each table, offline value vs live value')
    local any = false
    for _, name in ipairs(SPEC_ORDER) do
        local first = SPECS[name].copies[1]
        if first and first.mismatches and #first.mismatches > 0 then
            any = true
            for _, line in ipairs(first.mismatches) do add(name .. ': ' .. line) end
            if first.watch.differing > #first.mismatches then
                add(name .. ': ... ' .. (first.watch.differing - #first.mismatches) .. ' more')
            end
        end
        if first and first.missing and #first.missing > 0 then
            any = true
            add(name .. ': keys not in the live table, e.g. ' .. table.concat(first.missing, '; '))
        end
    end
    if not any then add('none') end
    add('')
    add('[stratagems] live rows; cooldown offset votes against the community snapshot')
    local listed = {}
    for _, r in ipairs(SPECS.StratagemSettings and SPECS.StratagemSettings.copies or {}) do
        if r.calibration then
            local votes = {}
            for offset = 84, 108, 4 do votes[#votes + 1] = '+' .. offset .. ':' .. r.calibration.votes[offset] end
            add(string.format('group at %s: known %d, uses@80 match %d, cooldown votes %s', hex(r.address),
                r.calibration.known, r.calibration.uses_ok, table.concat(votes, ' ')))
        end
        for _, line in ipairs(r.stratagems or {}) do
            if not listed[line] then
                listed[line] = true
                add('  ' .. line)
            end
        end
    end
    add('')
    add('[status effects] id=debug name (first copy)')
    local effects = SPECS.StatusEffectSettings and SPECS.StatusEffectSettings.copies[1]
    if effects and effects.names then
        add(table.concat(effects.names, ', '))
        for _, line in ipairs(effects.dumps or {}) do add('raw ' .. line) end
    else
        add('table not found')
    end
    add('')
    add('[attachment deltas]')
    local deltas = SPECS.ComponentEntityDeltaStorage and SPECS.ComponentEntityDeltaStorage.copies[1]
    if deltas and deltas.components then
        for _, line in ipairs(deltas.components) do add(line) end
    else
        add(deltas and ('PROBLEM: ' .. tostring(deltas.problem)) or 'table not found')
    end
    add('')
    add('[census] every LDLD block type seen in the last pass: type count bytes origins')
    local by_type, order = {}, {}
    for _, block in ipairs(census.list) do
        local entry = by_type[block.type]
        if not entry then
            entry = { type = block.type, count = 0, bytes = 0, origins = {} }
            by_type[block.type] = entry
            order[#order + 1] = entry
        end
        entry.count, entry.bytes = entry.count + 1, entry.bytes + block.size
        entry.origins[block.origin] = (entry.origins[block.origin] or 0) + 1
    end
    table.sort(order, function(x, y) return x.bytes > y.bytes end)
    for n, entry in ipairs(order) do
        if n > 400 then add('... ' .. (#order - 400) .. ' more types') break end
        local origins = {}
        for origin, count in pairs(entry.origins) do origins[#origins + 1] = origin .. 'x' .. count end
        table.sort(origins)
        local spec = SPEC_BY_TYPE[entry.type]
        add(string.format('%08X %d %.0f %s%s', entry.type, entry.count, entry.bytes, table.concat(origins, ','),
                          spec and (' ' .. spec.name) or ''))
    end
    add('')
    add('[history] round: frame, mode, blocks, wanted tables found')
    for _, line in ipairs(state.history or {}) do add(line) end
    return table.concat(L, '\r\n') .. '\r\n'
end

local function write_status()
    local ok, text = pcall(build_status)
    if not ok then
        log('status: ' .. tostring(text))
        text = 'FAILED - could not build the status report: ' .. tostring(text) .. '\r\n'
            .. MOD.title .. ' v' .. MOD.version .. '\r\n'
    end
    write_file(MOD.status, text)
    flush_log()
end

-- ---------------------------------------------------------------- rounds
local last_signature, last_sweep_at, resume_at = nil, 0, 0

local function wanted_signature()
    local parts, found = {}, 0
    for _, name in ipairs(SPEC_ORDER) do
        local copies = SPECS[name].copies
        if #copies > 0 then found = found + 1 end
        local addresses = {}
        for _, r in ipairs(copies) do addresses[#addresses + 1] = r.address end
        table.sort(addresses)
        parts[#parts + 1] = table.concat(addresses, ',')
    end
    return table.concat(parts, '|'), found
end

local function rounds()
    parse_data()
    write_status()
    local sweep_next, sweep_wanted = false, false
    while state.round < MAX_ROUNDS do
        state.round = state.round + 1
        local mode = 'fast'
        if state.round == 2 or sweep_next then mode = 'sweep' end
        sweep_next = false
        state.mode, state.phase = mode, 'scanning (' .. mode .. ')'
        enumerate(mode)
        if mode == 'sweep' then
            state.sweeps = state.sweeps + 1
            last_sweep_at = A.now()
        end
        state.phase = 'analyzing'
        analyze()
        local signature, found = wanted_signature()
        state.history = state.history or {}
        if #state.history < 120 then
            state.history[#state.history + 1] = string.format('%d: frame %d, %s, %d blocks, %d of %d tables%s',
                state.round, state.frame, mode, #census.list, found, #SPEC_ORDER,
                signature ~= last_signature and ', copies changed' or '')
        end
        -- the set of copies changed (mission load?): look everywhere again, but not more often
        -- than every SWEEP_GAP_SECONDS and not more than MAX_SWEEPS times
        if last_signature and signature ~= last_signature then sweep_wanted = true end
        if sweep_wanted and state.sweeps < MAX_SWEEPS and A.now() - last_sweep_at >= SWEEP_GAP_SECONDS then
            sweep_next, sweep_wanted = true, false
        end
        local changed = signature ~= last_signature or mode == 'sweep'
        last_signature = signature
        if state.round == 2 and not build.done then
            state.phase = 'identifying the build'
            identify_build()
            changed = true
        end
        state.phase = 'resting'
        if changed or state.round <= 2 or state.round % 15 == 0 then write_status() end
        if not sweep_next then
            resume_at = A.now() + (state.round == 1 and 0 or REST_SECONDS)
            coroutine.yield()
        end
    end
    state.phase = 'done'
    write_status()
end

-- ---------------------------------------------------------------- per frame
local worker = nil

local function retire()
    state.retired = true
    if state.unhook then pcall(state.unhook) end
end

local function tick()
    state.frame = state.frame + 1
    if state.frame < START_FRAME or state.frame % STEP_EVERY ~= 0 then return end
    local now = A.now()
    if now < resume_at then return end
    if not worker then worker = coroutine.create(rounds) end
    deadline = now + FRAME_BUDGET
    local ok, why = coroutine.resume(worker)
    local cost = A.now() - now
    state.busy_frames, state.busy_seconds = state.busy_frames + 1, state.busy_seconds + cost
    if cost > state.worst_frame then state.worst_frame = cost end
    if not ok then
        state.errors = state.errors + 1
        log('round ' .. state.round .. ' failed: ' .. tostring(why))
        worker = nil
        if state.errors >= 5 then
            state.phase, state.failure = 'gave_up', 'too many errors, last: ' .. tostring(why)
            write_status()
            retire()
        else
            resume_at = A.now() + 5
            write_status()
        end
    elseif coroutine.status(worker) == 'dead' then
        log('finished after ' .. state.round .. ' rounds')
        flush_log()
        retire()
    end
end

-- ---------------------------------------------------------------- startup
log(MOD.title .. ' v' .. MOD.version)
-- The API is built first (it only looks functions up) so that even a refusal below can be
-- written to our own folder.
local api_ok, api_failure = pcall(function()
    assert(ffi_ok and ffi, 'LuaJIT FFI is unavailable')
    assert(ffi.abi('64bit'), 'Windows x64 is required')
    A = build_api()
end)
if not api_ok then A = nil end
local ok, failure = pcall(function()
    local loader = rawget(_G, 'CowboyBingusModLoader')
    if type(loader) == 'table' and tonumber(loader.api) and tonumber(loader.api) < 1 then
        error('Bingus Shared Loader is too old (API ' .. tostring(loader.api) .. '); v15 or newer is required', 0)
    end
    if not api_ok then error(tostring(api_failure), 0) end
    if not float_selftest() then error('float decoder self-test failed', 0) end
    if type(rawget(_G, 'update')) ~= 'function' then error('the game update hook is unavailable', 0) end
    -- not fatal: reported in STATUS (a failure here means no memory read can work)
    state.self_read = A.u32(A.buffer_address) ~= nil
end)

if not ok then
    state.phase, state.failure = 'gave_up', tostring(failure)
    log('startup failed: ' .. tostring(failure))
    print('[' .. MOD.global .. '] ' .. tostring(failure))
    write_file(MOD.status, 'FAILED - ' .. tostring(failure) .. '\r\n' .. MOD.title .. ' v' .. MOD.version .. '\r\n')
    flush_log()
    return
end

log('armed; output in ' .. tostring(ensure_out_dir()))
write_file(MOD.status, 'WAITING - the scan starts a few seconds after launch (keep the game running)\r\n'
    .. MOD.title .. ' v' .. MOD.version .. '\r\n')
flush_log()

-- Guarded hook: other addons may wrap `update` after us, so we only restore it when we are
-- still the outermost wrapper; otherwise we stay in the chain and do nothing.
local original_update = update
local my_update
my_update = function(...)
    if not state.retired then
        local tick_ok, why = pcall(tick)
        if not tick_ok then
            state.errors = state.errors + 1
            log('tick: ' .. tostring(why))
            if state.errors >= 20 then retire() end
        end
    end
    return original_update(...)
end
state.unhook = function()
    if rawget(_G, 'update') == my_update then update = original_update end
end
update = my_update
